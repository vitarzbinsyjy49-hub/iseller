def has_placeholders(text: str) -> bool:
    """Остались ли в тексте незаполненные места.

    Пост с плейсхолдером публиковать нельзя: «[уточнить] — впишите ваши
    условия» в канале выглядит как забытый черновик и подрывает доверие
    сильнее, чем отсутствие поста.
    """
    return PLACEHOLDER in (text or "")


