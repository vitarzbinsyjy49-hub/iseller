# ---------------------------------------------------------------- конструктор кнопок

#: Типы кнопок, доступные в админке. Ссылки на менеджера, канал и разделы
#: прайса подставляются в момент публикации из настроек и из БД — поэтому в
#: посте хранится ОПИСАНИЕ кнопки, а не готовый URL: сменится ссылка менеджера,
#: и все посты подхватят новую, вместо того чтобы тащить вмороженную старую.
BUTTON_KINDS = ("catalog", "ai", "requests", "manager", "channel", "section", "url")

BUTTON_KIND_LABELS = {
    "catalog": "Каталог",
    "ai": "AI-подбор",
    "requests": "Мои заявки",
    "manager": "Менеджер",
    "channel": "Наш канал",
    "section": "Раздел прайса",
    "url": "Своя ссылка",
}


def resolve_button(
    spec: dict, *, bot_username: str, manager_url: str, channel_url: str,
    section_links: dict[str, str] | None = None,
) -> dict | None:
    """Описание кнопки -> кнопка Bot API. None, если ссылку получить не удалось.

    Кнопка без валидного URL не просто не показывается — Telegram отвергает
    ВСЁ сообщение (BUTTON_TYPE_INVALID / пустой url), поэтому нерешаемые
    кнопки молча выпадают, а пост уходит целиком.
    """
    from app.services.price_posts import deep_link

    text = (spec.get("text") or "").strip()
    kind = spec.get("kind")
    value = (spec.get("value") or "").strip()
    if not text or kind not in BUTTON_KINDS:
        return None

    if kind in ("catalog", "ai", "requests"):
        url = deep_link(bot_username, kind)
    elif kind == "manager":
        url = manager_url
    elif kind == "channel":
        url = channel_url
    elif kind == "section":
        # Ссылка на конкретный опубликованный прайс-пост, если он уже в канале;
        # иначе — вход в раздел через бота, чтобы кнопка не пропала совсем.
        url = (section_links or {}).get(value) or deep_link(bot_username, value)
    else:
        url = value

    url = (url or "").strip()
    return {"text": text, "url": url} if url.startswith("https://") else None


def build_keyboard(
    specs: list[dict] | None, *, bot_username: str, manager_url: str,
    channel_url: str = "", section_links: dict[str, str] | None = None,
) -> list[list[dict]]:
    """Собрать клавиатуру из описаний. Поле row задаёт группировку в ряды."""
    if not specs:
        return []
    rows: dict[int, list[dict]] = {}
    for index, spec in enumerate(specs):
        button = resolve_button(spec, bot_username=bot_username, manager_url=manager_url,
                                channel_url=channel_url, section_links=section_links)
        if button is None:
            continue
        rows.setdefault(int(spec.get("row", index)), []).append(button)
    return [rows[key] for key in sorted(rows) if rows[key]]


