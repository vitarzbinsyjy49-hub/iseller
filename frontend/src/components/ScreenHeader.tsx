/** Заголовок внутреннего экрана: крупный тает и остаётся видимым на desktop,
 *  компактный проявляется в липком баре — только на mobile/tablet.
 *
 *  Зачем. До этого каждый экран рисовал голый `<h1 className="text-2xl
 *  font-bold">` прямо в потоке, и он свободно уезжал ВВЕРХ под `.hero-top-inset`
 *  — фиксированную непрозрачную полосу под системной областью Telegram. Полоса
 *  режет содержимое жёсткой горизонтальной кромкой, и заголовок исчезал не
 *  растворяясь, а обрубленным пополам. На главной этого не видно никогда,
 *  потому что там заголовок ТАЕТ раньше, чем доезжает до полосы
 *  (lib/useCollapsingHeader.ts). Здесь тот же мотор отдаётся всем остальным
 *  экранам, и обрезка становится невозможной по построению: к моменту, когда
 *  заголовок дошёл бы до кромки, его уже нет.
 *
 *  Два узла — разная судьба на desktop. На `lg` нет ни `.hero-top-inset`, ни
 *  нижней навигации, и липкий бар там просто не нужен — он остаётся
 *  `lg:hidden`. А вот крупный заголовок обязан остаться ВИДИМЫМ: это
 *  единственное место, где написано название экрана, и без него на `lg`
 *  страница осталась бы вовсе без заголовка — ни на экране, ни в дереве
 *  доступности. Поэтому `lg:hidden` с крупного заголовка снят, а с ним и
 *  собственно anim: `[data-collapsing-title]` получает `opacity: 1 !important`
 *  и `transform: none !important` от брейкпоинта `lg` в index.css — мотор
 *  по-прежнему пишет туда инлайновые стили при прокрутке (для mobile), но на
 *  `lg` CSS с `!important` их перебивает, и заголовок держится на месте, не
 *  тая при скролле, хотя компенсирующего компактного бара там нет.
 *
 *  Почему фрагмент, а не обёртка. `position: sticky` действует только внутри
 *  коробки родителя. Оберни мы бар и заголовок в общий `<div>`, бар отлипал бы
 *  ровно на высоте этого div — то есть немедленно. Оба узла обязаны быть
 *  ПРЯМЫМИ детьми корня страницы; та же грабля уже описана у липкой шапки в
 *  pages/Home.tsx.
 *
 *  Кому НЕ нужен. Вкладочным экранам (Каталог, Профиль): их имя уже написано на
 *  подсвеченной вкладке внизу, и крупная надпись «Каталог» над каталогом —
 *  повтор, а не заголовок. Там `<h1>` просто удалён. Так же устроены и Telegram,
 *  и Ozon: имя раздела живёт в навигации, контент начинается сразу.
 *
 *  Использование — ref мотора вешается на КОРЕНЬ страницы:
 *
 *      const collapsing = useCollapsingHeader();
 *      <div ref={collapsing}>
 *        <ScreenHeader title="Корзина" subtitle="3 товара" />
 *        …
 *      </div>
 */
import type { ReactNode } from "react";

export default function ScreenHeader({
  title, subtitle, actions,
}: {
  title: string;
  /** Строка под заголовком: счётчик, пояснение. Именно она снимает у заголовка
   *  вид осиротевшей чёрной надписи — у него появляется контекст, а не только
   *  вес. Нечего сказать — не передавать; выдуманный подзаголовок хуже, чем
   *  никакого. */
  subtitle?: string;
  /** Правый край липкого бара: кнопки экрана, если они у него есть.
   *  Бар целиком `lg:hidden`, поэтому это место для действий, которые можно
   *  потерять на desktop без вреда (или у которых там есть другой вход) —
   *  для остального нужен отдельный, видимый на `lg` элемент. */
  actions?: ReactNode;
}) {
  return (
    <>
      {/* Липкий бар. Стекло в нём наливается покадрово по мере таяния заголовка
          — переменную --nav-glass пишет тот же мотор. Пока экран не тронут, бар
          прозрачен и не занимает собой места: под ним ещё ничего не проехало.
          lg:hidden — на desktop нет ни .hero-top-inset, ни нижней навигации,
          и подменять заголовок компактной версией там незачем. */}
      <header
        data-collapsing-nav
        className="app-navbar -mx-4 -mt-3 flex items-center gap-3 px-4 pb-2 pt-2 lg:hidden"
      >
        {/* aria-hidden: тот же текст уже есть в <h1> ниже, и opacity: 0 его из
            дерева доступности не убирает — оба узла видны скринридеру
            одновременно, и без aria-hidden название экрана звучало бы дважды
            подряд (тот же приём и по той же причине, что у мелкого заголовка
            в pages/Home.tsx). */}
        <span
          data-collapsing-smalltitle
          aria-hidden="true"
          style={{ opacity: 0 }}
          className="min-w-0 flex-1 truncate text-[15px] font-semibold tracking-tight"
        >
          {title}
        </span>
        {actions}
      </header>

      {/* Крупный заголовок.
          22px/600, а не 24px/700: это единственный тяжёлый элемент на экране,
          состоящем из белых карточек и средних насыщенностей, и в прежнем весе
          он читался как деталь чужого макета. Вес снижен, кегль выровнен по
          строке подзаголовка — заголовок остаётся главным, но перестаёт быть
          плитой. Растворяется при прокрутке на mobile/tablet
          (data-collapsing-title); на lg держится на месте — см. докстринг
          компонента выше и правило в index.css. БЕЗ lg:hidden: это
          единственный заголовок экрана, и на desktop его прятать нельзя. */}
      <div data-collapsing-title>
        <h1 className="text-[22px] font-semibold leading-tight tracking-tight [text-wrap:balance]">
          {title}
        </h1>
        {subtitle && <p className="mt-0.5 text-[13px] text-muted">{subtitle}</p>}
      </div>
    </>
  );
}
