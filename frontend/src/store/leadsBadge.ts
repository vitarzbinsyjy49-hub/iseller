/** Счётчик заявок и непросмотренных изменений по ним.
 *
 *  Зачем стор, а не состояние страницы. Цифру показывают ДВА места сразу —
 *  кнопка в профиле и точка на вкладке «Профиль» в нижней навигации, которая
 *  живёт в Layout и переживает переходы между страницами. Пока счёт лежал в
 *  Profile.tsx, второе место могло получить его только собственным запросом:
 *  два обращения к /leads/my на каждый заход в приложение ради одного и того
 *  же числа.
 *
 *  BottomNav зовёт refresh() при каждом монтировании — то есть на ЛЮБОМ первом
 *  экране приложения, не только на /profile. Это осознанно: точке на вкладке
 *  неоткуда узнать, что показывать, кроме как спросить сервер. Не убирать этот
 *  вызов, приняв его за случайный лишний запрос — без него точка на вкладке
 *  никогда не загорится, если человек ни разу не открывал профиль.
 *
 *  Раз оба места (BottomNav и Profile) зовут refresh() независимо и могут
 *  смонтироваться в одном рендер-цикле (человек открыл сразу /profile —
 *  реальный сценарий, см. обработку deep link ?roadmap=1 в Profile.tsx), стор
 *  обязан сам защищаться от дублирования сети:
 *
 *  - запрос «в полёте» переиспользуется — второй вызов получает тот же
 *    промис, а не запускает параллельный;
 *  - завершившийся запрос кэшируется на FRESH_MS: бейдж — подсветка, а не
 *    котировки, секундная точность ему не нужна, а повторный заход в профиль
 *    сразу после предыдущего не должен снова дёргать сеть.
 *
 *  Обе величины — активный промис и время последней успешной загрузки —
 *  держатся ВНЕ состояния zustand: это детали кэширования, а не то, на что
 *  должны перерисовываться подписчики.
 *
 *  Почему отметка о просмотре в localStorage, а не колонкой в users. Колонка
 *  дала бы синхронизацию между устройствами, но стоила бы мини-миграции и
 *  обязательного добавления в REQUIRED_SCHEMA бота — иначе он падает
 *  UndefinedColumn на первом же деплое. Всё это ради подсветки, которая живёт
 *  до первого открытия раздела, у пользователя, который почти всегда на одном
 *  устройстве. Понадобится синхронизация — поднимем отдельной задачей.
 */
import { create } from "zustand";

import { api } from "../lib/api";
import { seenMarkFor, unseenLeadCount, type LeadSeenLike } from "../lib/leads";

const SEEN_KEY = "leads_seen_at";

/** Сколько держим последний успешный ответ свежим. 60 секунд — не «быстро,
 *  насколько получится», а размер окна, в котором BottomNav и Profile почти
 *  наверняка оба смонтируются при одном открытии приложения. Бейдж сообщает
 *  «там что-то изменилось», а не текущее состояние на этот миг, — минута
 *  устаревания для такого сигнала не искажает его смысла. */
const FRESH_MS = 60_000;

/** Хранилище может быть недоступно (приватный режим, отключённые куки).
 *  Отсутствие отметки — не ошибка: бейдж просто не зажигается. */
function readSeen(): string | null {
  try {
    return localStorage.getItem(SEEN_KEY);
  } catch {
    return null;
  }
}

function writeSeen(iso: string): void {
  try {
    localStorage.setItem(SEEN_KEY, iso);
  } catch {
    /* подсветка — не то, ради чего стоит падать */
  }
}

type LeadsBadgeState = {
  /** Всего заявок. null — ещё не спрашивали. */
  total: number | null;
  /** Изменившихся с последнего просмотра. */
  unseen: number;
  refresh: (force?: boolean) => Promise<void>;
  markSeen: (leads?: LeadSeenLike[]) => void;
};

// Вне видимого состояния стора: детали кэширования, не то, на что должны
// перерисовываться подписчики (см. докстринг файла).
let inFlight: Promise<void> | null = null;
let lastFetchedAt = 0;

export const useLeadsBadge = create<LeadsBadgeState>((set) => ({
  total: null,
  unseen: 0,
  refresh: (force = false) => {
    if (!force && Date.now() - lastFetchedAt < FRESH_MS) return Promise.resolve();
    if (inFlight) return inFlight;

    inFlight = (async () => {
      try {
        const d = await api<{ leads: LeadSeenLike[] }>("/leads/my");
        set({ total: d.leads.length, unseen: unseenLeadCount(d.leads, readSeen()) });
        lastFetchedAt = Date.now();
      } catch {
        // Сбой запроса оставляет счётчик нейтральным. Ошибка в бейдже пугает
        // сильнее, чем отсутствие цифры, — то же правило, что у блока лояльности.
        // lastFetchedAt не трогаем: неудачная попытка не должна «застолбить»
        // окно свежести — следующий refresh() должен попробовать снова.
        set({ total: 0, unseen: 0 });
      } finally {
        inFlight = null;
      }
    })();
    return inFlight;
  },
  markSeen: (leads = []) => {
    // seenMarkFor штампует максимальный updated_at ЗАГРУЖЕННЫХ заявок, а не
    // часы устройства — см. докстринг lib/leads.ts. Requests.tsx зовёт это
    // сразу после успешной загрузки списка и передаёт его сюда; вызовы без
    // аргумента (если появятся) получают прежний запасной путь — текущее
    // время — через пустой массив.
    writeSeen(seenMarkFor(leads));
    set({ unseen: 0 });
  },
}));
