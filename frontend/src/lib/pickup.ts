/** Точка выдачи — один источник правды.
 *
 *  Адрес и часы были захардкожены в ДЕСЯТИ местах: карточка товара, корзина,
 *  форма заявки, онбординг, профиль, информация, легендарный товар, список
 *  заявок. Одиннадцатой копией стала бы строка в шапке главной — и в день, когда
 *  магазин переедет или сменит часы, половина экранов сказала бы правду, а
 *  половина осталась бы врать. Проект это уже проходил на списке категорий,
 *  который разъехался с базой и вёл в пустой каталог.
 *
 *  Почему константы, а не поле конфига с сервера. Точка выдачи одна и меняется
 *  раз в годы; заводить ради неё запрос, кэш и состояние загрузки — это цена
 *  без выгоды, а строка в шапке обязана быть на месте в первом же кадре. Когда
 *  точек станет несколько, отсюда уедет весь модуль целиком, а не россыпь строк
 *  по экранам.
 *
 *  Чистые функции: тесты идут в node без DOM (vitest.config.ts).
 */

export const PICKUP_PLACE = "Горбушка";
export const PICKUP_CITY = "Москва";

/** Часы работы, границы включительно по открытию и исключительно по закрытию:
 *  в 21:00 уже закрыто. */
export const PICKUP_OPEN_HOUR = 10;
export const PICKUP_CLOSE_HOUR = 21;

/** «Горбушка, Москва» — для мест, где нужен полный адрес одной строкой. */
export const PICKUP_ADDRESS = `${PICKUP_PLACE}, ${PICKUP_CITY}`;

/** «10:00–21:00» — часы одной строкой. Тире здесь длинное (–), как в остальных
 *  диапазонах приложения. */
export const PICKUP_HOURS = `${PICKUP_OPEN_HOUR}:00–${PICKUP_CLOSE_HOUR}:00`;

/** Час по Москве, независимо от того, где стоят часы телефона.
 *
 *  Точка выдачи физически в Москве, и «работает ли она прямо сейчас» — вопрос
 *  про московское время, а не про местное у покупателя. Человек из Владивостока,
 *  открывший приложение в свои 9 утра, не должен видеть «закрыто»: в Москве
 *  в этот момент 2 часа ночи вчерашнего дня, но и наоборот — в свои 23:00 он
 *  не должен видеть «открыто».
 *
 *  Intl доступен и в браузере, и в node, поэтому функция тестируема без DOM.
 *  Отказ (экзотическое окружение без базы часовых поясов) отдаёт локальный час:
 *  соврать на несколько часов лучше, чем упасть на строке в шапке.
 */
export function moscowHour(now: Date): number {
  try {
    const h = new Intl.DateTimeFormat("ru-RU", {
      timeZone: "Europe/Moscow",
      hour: "numeric",
      hour12: false,
    }).format(now);
    const n = parseInt(h, 10);
    return Number.isFinite(n) ? n % 24 : now.getHours();
  } catch {
    return now.getHours();
  }
}

export type PickupStatus = {
  open: boolean;
  /** Короткая подпись рядом с местом: «до 21:00» или «с 10:00». */
  label: string;
};

/** Открыта ли точка выдачи в этот час и что написать рядом.
 *
 *  Подпись отвечает на СЛЕДУЮЩИЙ вопрос, а не повторяет предыдущий: если
 *  открыто — до скольких успеть, если закрыто — с какого часа приходить.
 *  «Открыто» и «Закрыто» словами тут не нужны: они занимают место и не говорят
 *  ничего сверх времени, которое всё равно придётся написать.
 */
export function pickupStatus(hour: number): PickupStatus {
  const open = hour >= PICKUP_OPEN_HOUR && hour < PICKUP_CLOSE_HOUR;
  return {
    open,
    label: open ? `до ${PICKUP_CLOSE_HOUR}:00` : `с ${PICKUP_OPEN_HOUR}:00`,
  };
}
