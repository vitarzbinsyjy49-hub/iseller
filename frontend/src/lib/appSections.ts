/** Раскладка клавиатуры: латинская буква → та, что напечаталась бы на русской.
 *
 *  Нужна для случая, который в Telegram случается постоянно: человек набирает
 *  «pfzdrb», не переключив язык, и получает пустую выдачу вместо «Заявки».
 *  Таблица односторонняя (лат → рус) намеренно: запрос кириллицей в латиницу
 *  переводить незачем — все наши синонимы и так русские, кроме нескольких
 *  заимствований, которые лежат в реестре как есть.
 */
const LAYOUT_LAT_TO_RU: Record<string, string> = {
  q: "й", w: "ц", e: "у", r: "к", t: "е", y: "н", u: "г", i: "ш", o: "щ", p: "з",
  "[": "х", "]": "ъ", a: "ф", s: "ы", d: "в", f: "а", g: "п", h: "р", j: "о",
  k: "л", l: "д", ";": "ж", "'": "э", z: "я", x: "ч", c: "с", v: "м", b: "и",
  n: "т", m: "ь", ",": "б", ".": "ю",
};

/** Приводит запрос к сравнимому виду: нижний регистр, ё→е, схлопнутые пробелы.
 *
 *  ё→е — не педантизм: «ещё» и «еще» человек пишет вперемешку, а мы не можем
 *  требовать от него попасть в наше написание синонима.
 */
export function normalizeQuery(q: string): string {
  return q.toLowerCase().replace(/ё/g, "е").replace(/\s+/g, " ").trim();
}

/** Тот же запрос, как если бы его набрали в русской раскладке. Символы, которых
 *  нет в таблице (цифры, кириллица, пробелы), остаются собой. */
export function toRuLayout(q: string): string {
  let out = "";
  for (const ch of q) out += LAYOUT_LAT_TO_RU[ch] ?? ch;
  return out;
}

/** Совпадает ли раздел с запросом.
 *
 *  Совпадение по ПРЕФИКСУ слова, а не по вхождению подстроки: «ка» должно
 *  находить «Каталог», но «лог» находить его не должно — иначе выдача
 *  наполняется случайными попаданиями в середину слов и перестаёт читаться.
 */
function sectionMatches(section: AppSection, q: string): boolean {
  const haystacks = [section.label, ...section.synonyms].map(normalizeQuery);
  return haystacks.some((h) => h.split(" ").some((word) => word.startsWith(q)));
}

/** Минимальная длина запроса, с которой ищем разделы.
 *
 *  Одна буква даёт половину реестра — это не подсказка, а шум поверх товаров,
 *  ради которых поиск и открывали. */
export const MIN_SECTION_QUERY_LEN = 2;

/** Разделы, подходящие под запрос. Пустой или слишком короткий запрос даёт
 *  пустой список: показывать «все разделы» в момент набора текста значит
 *  оттеснить товарную выдачу вниз ровно тогда, когда её ждут.
 *
 *  Запрос проверяется дважды — как набран и как он выглядел бы в русской
 *  раскладке. Порядок результатов — порядок реестра: он расставлен по
 *  ожидаемой частоте, и сортировать по длине совпадения значило бы выдумать
 *  релевантность там, где её нечем измерить.
 */
export function searchAppSections(query: string, limit = 4): AppSection[] {
  const q = normalizeQuery(query);
  if (q.length < MIN_SECTION_QUERY_LEN) return [];
  const alt = toRuLayout(q);
  const out: AppSection[] = [];
  for (const s of APP_SECTIONS) {
    if (sectionMatches(s, q) || (alt !== q && sectionMatches(s, alt))) out.push(s);
    if (out.length >= limit) break;
  }
  return out;
}
