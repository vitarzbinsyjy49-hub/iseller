/** Разделы приложения как объекты поиска.
 *
 *  Зачем. Круг поиска в нижней навигации доступен с каждого экрана, и человек
 *  набирает в нём не только «iPhone». «Заявки», «корзина», «баллы» — такие же
 *  законные запросы, но каталог о них ничего не знает и честно отвечает
 *  «ничего не нашлось». Раздел приложения — не товар, и искать его товарным
 *  поиском нельзя; поэтому у него свой маленький реестр здесь.
 *
 *  Реестр РУЧНОЙ и это осознанно. Вывести его из маршрутов нельзя: маршрут
 *  знает путь, но не знает, как человек назовёт то, что за ним. «Мои заявки»
 *  ищут словом «заказы», избранное — «сохранённые», баллы — «бонусы». Синонимы
 *  и есть содержание этого файла, а не список путей.
 *
 *  Правило пополнения: сюда попадает только раздел, у которого ЕСТЬ маршрут в
 *  App.tsx. Ссылка в никуда из поиска хуже отсутствия результата — она выглядит
 *  как поломка, а не как «не нашлось».
 *
 *  Чистые функции: тесты идут в node без DOM (vitest.config.ts).
 */

