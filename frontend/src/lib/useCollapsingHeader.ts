/** Крупный заголовок главной, который тает под липкой шапкой при прокрутке.
 *
 *  Зачем. Верх главной был плоским: пять рядов подряд (логотип, слоган, поиск,
 *  оси с курсом, категории), все примерно одного веса, и ничего из этого не
 *  реагировало на прокрутку. Экран читался как веб-страница в вебвью, а не как
 *  приложение. Здесь заводится ровно одно недостающее движение — то самое,
 *  которым живут App Store, Почта и Настройки: заголовок крупный, пока человек
 *  стоит наверху, и уходит под шапку, как только он поехал за товаром. Шапка в
 *  этот же момент проявляется стеклом — до того она не нужна, под ней ничего
 *  нет.
 *
 *  Почему прогресс, а не «свёрнуто / развёрнуто». Бинарное состояние потребовало
 *  бы перехода между двумя видами, а переход здесь сделать нечем: этот webview
 *  гасит декларативную анимацию (см. lib/motion.ts и useHideOnScroll.ts).
 *  Непрерывная привязка к позиции прокрутки эту проблему обходит НЕ хитростью, а
 *  по существу: анимации нет вовсе, каждый кадр значение считается из scrollTop.
 *  Гасить нечего. Заодно это ближе к оригиналу — на iOS заголовок тоже тает
 *  плавно, а не переключается.
 *
 *  Почему без useState. Прокрутка — самое частое событие в приложении, а
 *  главная тяжёлая (лента карточек, сценарии, баннеры). Ре-рендер страницы на
 *  каждый кадр прокрутки — это подтормаживание ровно в момент движения. Здесь
 *  меняются две инлайновые величины на двух узлах, до React дело не доходит.
 *
 *  Что двигаем. Только `opacity` и `transform` у заголовка и альфа фона у
 *  шапки — свойства, которые композитор считает без перерисовки страницы.
 */
import { useCallback, useRef } from "react";

import { prefersReducedMotion } from "./motion";
import { scrollParentOf } from "./useHideOnScroll";

/** За сколько пикселей прокрутки заголовок исчезает полностью.
 *
 *  72 — это чуть больше его собственной высоты (26/32 плюс отступ). Смысл в
 *  том, чтобы заголовок успел раствориться РОВНО к моменту, когда он уходит под
 *  шапку, а не заметно раньше (мигание пустого места) и не позже (текст видно
 *  сквозь стекло). */
export const COLLAPSE_DISTANCE_PX = 72;

/** Насколько заголовок ушёл под шапку: 0 — покой, 1 — убран, шапка стала
 *  стеклом.
 *
 *  Вся логика модуля — здесь, отдельной чистой функцией: остальное в файле это
 *  подписки и запись в DOM, которые тестировать нечем. Тот же приём, что у
 *  `nextToolbarHidden` в useHideOnScroll. */
export function collapseProgress(scrollTop: number, distance = COLLAPSE_DISTANCE_PX): number {
  // Дробные и отрицательные позиции реальны: iOS отдаёт нецелый scrollTop, а
  // при оттягивании ленты вниз он уходит в минус.
  if (!(distance > 0)) return scrollTop > 0 ? 1 : 0;
  const raw = scrollTop / distance;
  return raw < 0 ? 0 : raw > 1 ? 1 : raw;
}

/** Насколько заголовок приподнимается, пока тает. Маленькое число намеренно:
 *  это доводка, а не самостоятельное движение — заметить его должен только тот,
 *  кто ищет. */
const TITLE_LIFT_PX = 6;

/** Порог, ниже которого шапка вообще не претендует на стекло.
 *
 *  Нужен из-за цены `backdrop-filter`: в покое свойство должно ОТСУТСТВОВАТЬ, а
 *  не стоять нулём. `blur(0px)` всё равно заставляет браузер завести слой
 *  подложки и пересчитывать его на каждый кадр прокрутки — на слабом телефоне
 *  это ровно тот случай, когда «незаметный эффект» стоит кадров. */
const GLASS_ON_AT = 0.01;

/** Меньшая разница прогресса до DOM не доезжает: на кадр приходится доля
 *  пикселя, глазу она не видна, а запись в стиль — это работа. */
const PROGRESS_EPS = 0.008;

/** Ref-колбэк на КОНТЕЙНЕР верха. Внутри он сам находит два узла по
 *  data-атрибутам: `data-collapsing-nav` (липкая шапка) и
 *  `data-collapsing-title` (крупный заголовок). Так у вызывающей стороны один
 *  ref вместо трёх, а разметка остаётся читаемой — по атрибуту в JSX видно, что
 *  элемент участвует в схлопывании.
 *
 *  Подписку снимает сам ref-колбэк: React вызывает его с null, когда узел уходит
 *  из DOM. Отдельного useEffect здесь быть НЕ должно — в StrictMode его cleanup
 *  убивал бы подписку, а ref-колбэк заново не вызывался (узел-то на месте). Эта
 *  грабля уже поймана на живом стенде в useHideOnScroll. */
export function useCollapsingHeader() {
  const cleanup = useRef<(() => void) | null>(null);

  return useCallback((el: HTMLElement | null) => {
    cleanup.current?.();
    cleanup.current = null;
    if (!el) return;

    const scroller = scrollParentOf(el);
    if (!scroller) return;

    const nav = el.querySelector<HTMLElement>("[data-collapsing-nav]");
    const title = el.querySelector<HTMLElement>("[data-collapsing-title]");
    // Мелкий заголовок в слоте, освободившемся от логотипа. Ищется здесь же и
    // тем же способом: у вызывающей стороны остаётся один ref, а участие узла
    // в схлопывании по-прежнему видно по атрибуту прямо в JSX.
    const small = el.querySelector<HTMLElement>("[data-collapsing-smalltitle]");
    if (!nav && !title) return;

    // Подъём заголовка — единственное здесь, что является ДВИЖЕНИЕМ, а не
    // сменой прозрачности. При «уменьшить движение» он и снимается; растворение
    // остаётся, потому что убрать движение — это не убрать событие (lib/motion).
    const lift = prefersReducedMotion() ? 0 : TITLE_LIFT_PX;

    let raf = 0;
    let last = -1;

    const apply = () => {
      raf = 0;
      const p = collapseProgress(scroller.scrollTop);
      // Края пропускаем всегда: именно на них снимается backdrop-filter и
      // дорисовывается последний процент прозрачности.
      const atEdge = p === 0 || p === 1;
      if (!atEdge && Math.abs(p - last) < PROGRESS_EPS) return;
      last = p;

      if (nav) {
        nav.style.setProperty("--nav-glass", p.toFixed(3));
        const glass = p > GLASS_ON_AT;
        if (glass) nav.dataset.glass = "on";
        else delete nav.dataset.glass;
      }
      if (title) {
        title.style.opacity = (1 - p).toFixed(3);
        title.style.transform = p && lift ? `translate3d(0, ${(-lift * p).toFixed(2)}px, 0)` : "";
      }
      // Появляется во ВТОРОЙ половине таяния крупного. Если вести мелкий тем же
      // обратным прогрессом от нуля, обе фразы половину пути видны
      // одновременно и читаются как дублирование, а не как передача эстафеты.
      // Только opacity: движение здесь уже есть у крупного заголовка, второе
      // на тех же 72 пикселях превратило бы передачу в суету.
      if (small) small.style.opacity = Math.max(0, (p - 0.5) * 2).toFixed(3);
    };

    // Первый расчёт синхронно: возврат на главную из карточки товара
    // восстанавливает позицию прокрутки (см. Layout), и шапка обязана приехать
    // уже в нужном виде, а не проявиться после первого движения пальцем.
    apply();

    // rAF-коалесценция: сколько бы событий прокрутки ни пришло за кадр, стили
    // пишем один раз. Тот же приём, что у useHideOnScroll и syncViewportVars.
    const onScroll = () => {
      if (raf) return;
      raf = requestAnimationFrame(apply);
    };
    scroller.addEventListener("scroll", onScroll, { passive: true });

    cleanup.current = () => {
      scroller.removeEventListener("scroll", onScroll);
      if (raf) cancelAnimationFrame(raf);
      if (nav) {
        nav.style.removeProperty("--nav-glass");
        delete nav.dataset.glass;
      }
      if (title) {
        title.style.opacity = "";
        title.style.transform = "";
      }
      if (small) {
        small.style.opacity = "";
      }
    };
  }, []);
}
