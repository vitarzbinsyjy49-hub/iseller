/** Кэш ответов витрины между экранами.
 *
 *  Зачем. Каждое переключение таба ходило в сеть заново: возврат на главную —
 *  пять запросов, вход в каталог — три, и так каждый раз. Данные при этом те
 *  же самые: товары и категории не меняются за то время, пока человек сходил
 *  в карточку и вернулся. Экран платил скелетоном за то, что уже знал.
 *
 *  Как. `@tanstack/react-query` в проекте стоял с самого начала и был подключён
 *  в main.tsx, но страницы ходили мимо него — напрямую через `api()`. Здесь его
 *  кэш и используется, но БЕЗ переписывания экранов на `useQuery`: `cachedApi`
 *  подменяет собой `api` в месте вызова, а всё остальное (состояния, ошибки,
 *  повторы) у экрана остаётся своё. Разница в одном слове на вызов — и потому
 *  правка не может тихо поменять поведение экрана, как это сделал бы перенос
 *  всей загрузки на чужие хуки.
 *
 *  Что кэшируется и что НЕТ. Только витрина: товары, категории, бренды,
 *  главная, подборки. Личное состояние — корзина, избранное, заявки, баллы —
 *  ходит по-прежнему через `api()` напрямую и кэша не видит. Эти данные
 *  человек меняет своими же действиями, и показать их из кэша значит показать
 *  неправду сразу после нажатия. Экономии там всё равно почти нет: один-два
 *  запроса против пяти у витрины.
 *
 *  Одинаковые запросы в один момент времени тоже схлопываются в один — этим
 *  занимается сам react-query по ключу. Ключ — сам путь запроса: два разных
 *  пути это два разных ответа, а одинаковые (та же категория, та же
 *  сортировка) обязаны быть одним.
 */
import { QueryClient } from "@tanstack/react-query";
import { api } from "./api";

/** Сколько ответ витрины считается свежим.
 *
 *  Минута — это ровно тот масштаб, на котором человек уходит в карточку товара
 *  и возвращается, листает табы, открывает корзину и идёт назад. Внутри него
 *  сеть не трогаем вовсе. Больше брать нельзя: цены и остатки правят в админке
 *  руками, и «свежесть» на пять минут означала бы, что после правки витрина
 *  врёт ещё пять минут.
 */
const STALE_MS = 60_000;

/** Сколько ответ лежит в памяти после того, как перестал быть нужен. Пережить
 *  он должен уход с экрана и возврат — иначе кэш не работает ровно в том
 *  случае, ради которого заведён. */
const GC_MS = 30 * 60_000;

export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      retry: 1,
      // Внутри Telegram фокус приходит и уходит на каждый сворачивание-
      // разворачивание клавиатуры; перезапрос на фокус здесь означал бы
      // сеть на пустом месте.
      refetchOnWindowFocus: false,
      staleTime: STALE_MS,
      gcTime: GC_MS,
    },
  },
});

/** Ключ запроса — это сам путь. Префикс "api" отделяет его от ключей, которые
 *  однажды заведёт кто-то ещё. */
const keyFor = (path: string) => ["api", path] as const;

/**
 * `api()`, но с кэшем: свежий ответ отдаётся из памяти, устаревший
 * перезапрашивается, одновременные одинаковые запросы схлопываются в один.
 *
 * Подпись повторяет `api()` намеренно — заменить вызов можно, не трогая ничего
 * вокруг. Сигнал отмены прокидывается как есть: экран каталога отменяет свой
 * предыдущий запрос сам, и отнимать у него это право кэш не должен.
 */
export function cachedApi<T>(path: string, options: RequestInit = {}): Promise<T> {
  return queryClient.fetchQuery({
    queryKey: keyFor(path),
    queryFn: () => api<T>(path, options),
  });
}

/**
 * Фоновый прогрев: запрос уходит заранее и кладётся в тот же кэш, откуда его
 * потом возьмёт `cachedApi`. Ошибку глотает молча — это догадка о том, куда
 * человек собирается, и провалившаяся догадка не должна ничего ломать.
 */
export function prefetchApi(path: string): void {
  void queryClient.prefetchQuery({
    queryKey: keyFor(path),
    queryFn: () => api(path),
  }).catch(() => {});
}

/** Пометить кэшированные ответы устаревшими — по точному пути или по началу
 *  пути. Нужно там, где витрина меняется от действий самого человека: открыл
 *  товар — «недавно смотрели» уже другое. */
export function invalidateApi(prefix: string): void {
  void queryClient.invalidateQueries({
    predicate: (q) => {
      const [scope, path] = q.queryKey as readonly [string, string];
      return scope === "api" && typeof path === "string" && path.startsWith(prefix);
    },
  });
}

/** Пути витрины, которые греются заранее И запрашиваются экраном.
 *
 *  Один литерал на обе стороны — это не стилистика. Ключ кэша здесь сам путь,
 *  поэтому прогрев работает только при совпадении СИМВОЛ В СИМВОЛ: разойдись
 *  строки на `?limit=10` против `?limit=12` — и обе стороны продолжат честно
 *  работать, просто ускорения не будет, а увидеть это по коду нельзя. Пути,
 *  которые греть нечем (список товаров собирается из фильтров в URL, карточка
 *  зависит от id), сюда не входят и живут по месту.
 */
export const SHOP = {
  home: "/home",
  feed: "/catalog/feed",
  categories: "/catalog/categories",
  brands: "/catalog/brands",
} as const;
