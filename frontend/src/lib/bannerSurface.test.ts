import { describe, expect, it } from "vitest";
import { edgeColor, inkOn, SURFACE_SAMPLE } from "./bannerSurface";

/** Подложка баннера берётся из самой фотографии, а цвет текста считается по её
 *  яркости. Это и есть весь смысл: администратор загружает что угодно, а
 *  читаемость не зависит от того, угадал ли он с картинкой. */

describe("edgeColor", () => {
  /** Пиксели как их отдаёт canvas: RGBA подряд, строка за строкой. */
  function pixels(rows: [number, number, number][]): Uint8ClampedArray {
    const out: number[] = [];
    for (const [r, g, b] of rows) out.push(r, g, b, 255);
    return new Uint8ClampedArray(out);
  }

  it("усредняет выборку", () => {
    expect(edgeColor(pixels([[100, 100, 100], [200, 200, 200]]))).toEqual([150, 150, 150]);
  });

  it("прозрачные пиксели не участвуют", () => {
    // Логотип с альфой: под прозрачным пикселем в canvas лежит чёрный, и
    // усреднив его вместе со всеми, мы получили бы подложку темнее картинки.
    const data = new Uint8ClampedArray([200, 200, 200, 255, 0, 0, 0, 0]);
    expect(edgeColor(data)).toEqual([200, 200, 200]);
  });

  it("пустая выборка — null, а не чёрный", () => {
    // Картинка не загрузилась или целиком прозрачна. Вернуть чёрный значило бы
    // покрасить баннер в чёрный молча; null — сигнал «оставь как было».
    expect(edgeColor(new Uint8ClampedArray([]))).toBeNull();
    expect(edgeColor(new Uint8ClampedArray([10, 10, 10, 0]))).toBeNull();
  });
});

describe("inkOn", () => {
  it("на светлой подложке — тёмный текст", () => {
    expect(inkOn([240, 235, 230])).toBe("dark");
  });

  it("на тёмной подложке — светлый", () => {
    expect(inkOn([30, 40, 60])).toBe("light");
  });

  it("порог считается по яркости, а не по сумме каналов", () => {
    // Чистый синий и чистый зелёный имеют одинаковую сумму каналов, но глаз
    // видит зелёный ВТРОЕ светлее. Сложи каналы — и на синем окажется тёмный
    // текст, которого на нём не прочитать.
    expect(inkOn([0, 0, 255])).toBe("light");
    expect(inkOn([0, 255, 0])).toBe("dark");
  });

  it("серый у порога решается в пользу светлого текста", () => {
    // Спорная середина опаснее для тёмного: тёмный на среднем сером даёт
    // меньший контраст, чем белый на нём же.
    expect(inkOn([128, 128, 128])).toBe("light");
  });
});

describe("SURFACE_SAMPLE", () => {
  it("выборка берётся у ЛЕВОГО края", () => {
    // Текст лежит слева, и подложка обязана совпадать именно с тем, что под
    // ним. Среднее по всей картинке дало бы цвет, которого у текста нет.
    expect(SURFACE_SAMPLE.width).toBeLessThanOrEqual(4);
    expect(SURFACE_SAMPLE.x).toBe(0);
  });
});
