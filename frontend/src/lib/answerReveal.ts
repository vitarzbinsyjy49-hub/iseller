/** Плавный показ ответа AI: сначала «набирается» текст, потом прикладываются
 *  карточки.
 *
 *  Зачем вынесено из компонента: тайминги — единственное, что здесь можно
 *  сломать незаметно, а vitest в проекте работает без DOM (только чистые
 *  функции). Компонент остаётся тонким: считает время, спрашивает у этих
 *  функций сколько символов показать, и всё.
 *
 *  Почему не посимвольная скорость («N знаков в секунду»): ответы AI бывают и
 *  200, и 900 символов. При фиксированной скорости короткий ответ мелькнёт, а
 *  длинный заставит ждать несколько секунд после того, как данные УЖЕ пришли —
 *  ожидание на пустом месте. Поэтому длительность зажата между полом и потолком.
 *
 *  Важно понимать масштаб: окно масштабирования — примерно 39-311 символов
 *  (пол/MS_PER_CHAR и потолок/MS_PER_CHAR). Ответ длиннее набирается за
 *  постоянные REVEAL_MAX_MS: скорость набора — вопрос читаемости, а не длины.
 *
 *  Потолок поднят с 1500 до 2800мс (и шаг с 7 до 9мс) осознанно. При прежних
 *  числах ответ на 600 символов набирался со скоростью 400 знаков в секунду —
 *  формально «печатался», а глазом читался как мгновенно возникший блок текста.
 *  Настоящего стриминга у нас нет и не предвидится: ответ приходит одним JSON
 *  со схемой, и разбирать его по кускам значит держать инкрементальный парсер
 *  ради анимации. Поэтому набор — единственный инструмент, и он должен быть
 *  заметен. Дальше поднимать нельзя: данные уже в браузере, и каждая лишняя
 *  сотня миллисекунд — ожидание на пустом месте.
 */

/** Пол и потолок длительности набора. 350мс — ниже этого текст не «набирается»,
 *  а мигает; 1500мс — выше этого пользователь ждёт зря, данные уже в браузере. */
export const REVEAL_MIN_MS = 350;
export const REVEAL_MAX_MS = 2800;
/** Ориентир для средней длины ответа (~250-600 символов). */
export const REVEAL_MS_PER_CHAR = 9;

/** Потолок набора, когда система просит меньше движения.
 *
 *  Именно потолок, а не отключение. Текст при наборе никуда не движется — он
 *  проявляется, и укачать этим нельзя; ровно по этой границе проведено
 *  требование WCAG. Раньше набор здесь выключался целиком, и в Telegram на
 *  телефоне с включённой настройкой ответ возникал стеной — человек жаловался
 *  не на «слишком много анимации», а на её отсутствие. Но и растягивать
 *  незачем: просьбу пользователя сокращаем, а не игнорируем. */
export const REVEAL_REDUCED_MAX_MS = 1000;

/** Сколько всего длится набор текста такой длины. */
export function revealDurationMs(length: number, reduced = false): number {
  if (length <= 0) return 0;
  const ceiling = reduced ? REVEAL_REDUCED_MAX_MS : REVEAL_MAX_MS;
  return Math.min(ceiling, Math.max(REVEAL_MIN_MS, length * REVEAL_MS_PER_CHAR));
}

/** Сколько символов показано к моменту elapsedMs. Линейно: набор текста должен
 *  идти ровно, ускорение к концу читается как рывок. */
export function revealedChars(length: number, elapsedMs: number, reduced = false): number {
  if (length <= 0) return 0;
  if (elapsedMs <= 0) return 0;
  const total = revealDurationMs(length, reduced);
  if (elapsedMs >= total) return length;
  return Math.round((elapsedMs / total) * length);
}

/** Система просит меньше движения. Набор от этого не выключается — только
 *  укорачивается (см. REVEAL_REDUCED_MAX_MS). Движение убирает CSS-блок
 *  `prefers-reduced-motion`: там гасятся смещения и масштаб, а проявление
 *  остаётся. */
export function prefersReducedMotion(): boolean {
  if (typeof window === "undefined" || typeof window.matchMedia !== "function") return false;
  return window.matchMedia("(prefers-reduced-motion: reduce)").matches;
}
