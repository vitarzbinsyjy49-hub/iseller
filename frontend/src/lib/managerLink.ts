/** Ссылка на менеджера с подставленным текстом.
 *
 *  ===== Что Telegram умеет, а что нет =====
 *
 *  `t.me/<кто-то>?text=...` кладёт текст в ПОЛЕ ВВОДА открывшегося чата.
 *  Отправляет его человек сам. Отправить за него нельзя — и не нужно: письмо,
 *  ушедшее от твоего имени без твоего нажатия, это то, за что приложения
 *  удаляют. Поэтому смысл подстановки не в экономии тапа, а в снятии барьера
 *  «с чего начать»: именно он, а не лишнее нажатие, мешает людям написать.
 *
 *  Параметр `text` для личных аккаунтов работает во всех клиентах Telegram, но
 *  в официальной документации диплинков его нет — он держится на практике.
 *  Поэтому деградация обязана быть безвредной: не сработает — чат просто
 *  откроется пустым, как открывался раньше. Ломаться тут нечему.
 *
 *  ===== Почему артикул в тексте =====
 *
 *  Он превращает «здравствуйте, интересует айфон» в запрос, на который можно
 *  ответить сразу. Без него первым сообщением менеджера всегда будет «а какой
 *  именно?» — то есть кнопка экономит человеку не тап, а целый круг переписки.
 */

/** Минимум, который нужен от товара. Шире брать нечего: всё остальное менеджер
 *  всё равно смотрит в админке по артикулу. */
export type ManagerProduct = {
  title: string;
  /** null — цену подтверждает менеджер (предзаказ). */
  price: number | null;
  /** null — артикула нет; тогда его в тексте не будет вовсе. */
  sku: string | null;
};

const RUB = new Intl.NumberFormat("ru-RU", { maximumFractionDigits: 0 });

/** Текст первого сообщения. */
export function managerMessage(product: ManagerProduct | null): string {
  if (!product) return "Здравствуйте! Хочу проконсультироваться по технике.";

  // Цена — только если она есть. У предзаказа её нет, и подставить «0 ₽» или
  // прочерк значило бы отправить менеджеру заведомую чушь от имени покупателя.
  const price = product.price != null ? `, ${RUB.format(product.price)} ₽` : "";
  const sku = product.sku ? ` (артикул ${product.sku})` : "";
  return `Здравствуйте! Интересует ${product.title}${price}${sku}. Подскажите по наличию и срокам?`;
}

/** Ссылка с подставленным текстом.
 *
 *  Пустой адрес остаётся пустым: конфиг мог не доехать, и вызывающий код в этом
 *  случае уводит в контакты. Вернуть «?text=...» без адреса значило бы отдать
 *  строку, которую openExternalLink попробует открыть.
 *
 *  Готовый `text` в адресе не перетирается: ссылку настраивает владелец в .env,
 *  и если он дописал туда свой текст — так и хотел.
 */
export function managerLink(base: string | undefined | null, product: ManagerProduct | null): string {
  if (!base) return "";
  const sep = base.includes("?") ? "&" : "?";
  if (/[?&]text=/.test(base)) return base;
  return `${base}${sep}text=${encodeURIComponent(managerMessage(product))}`;
}
