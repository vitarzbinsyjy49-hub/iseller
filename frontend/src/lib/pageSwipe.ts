/** Свайп-навигация между страницами (v5.5.0) — чистая логика, тестируется без DOM.
 *
 *  Модель гибридная и держится на одном различии: вкладка или вложенный экран.
 *
 *  - Пять корневых вкладок (те же и в том же порядке, что в BottomNav) — это
 *    ПЛОСКОСТЬ: свайп влево/вправо переходит к соседней вкладке, как листание
 *    страниц. Порядок вкладок пользователь и так видит внизу экрана, поэтому
 *    жест предсказуем: слева от «Каталога» всегда «Главная».
 *  - Вложенные экраны (карточка товара, избранное, история) — это ГЛУБИНА:
 *    туда попадают из вкладки, и обратно ведёт единственное осмысленное
 *    действие — назад по истории. Соседей у такого экрана нет, поэтому свайп
 *    влево там не делает ничего.
 *
 *  Жест «назад» на вложенном экране требует старта от левого края (как в iOS).
 *  Причина не в эстетике: вложенные экраны полны горизонтального контента
 *  (галерея фото товара, ленты «похожие»), и свайп из середины экрана почти
 *  всегда адресован контенту, а не навигации. На вкладках такого ограничения
 *  нет — там жест ловится из любого места, а конфликтующие зоны отсекаются
 *  отдельно, по признаку «жест начался внутри горизонтального скроллера».
 */

/** Корневые вкладки в порядке BottomNav — он же порядок листания. */
export const SWIPE_TABS = ["/", "/catalog", "/ai", "/requests", "/profile"] as const;

/** Направление движения ПАЛЬЦА (не страницы). */
export type SwipeDirection = "left" | "right";

export type SwipeNav =
  | { kind: "tab"; to: string }
  | { kind: "back" }
  | null;

/** Ширина зоны у левого края, откуда начинается жест «назад» (px). */
export const EDGE_ZONE = 28;

/** Индекс вкладки для пути, или -1 если это не корневая вкладка.
 *  «/» матчится точно, остальные — по префиксу, как в BottomNav. */
export function tabIndexOf(pathname: string): number {
  return SWIPE_TABS.findIndex((tab) =>
    tab === "/" ? pathname === "/" : pathname === tab || pathname.startsWith(`${tab}/`),
  );
}

/** Куда ведёт завершённый горизонтальный жест — или null, если никуда. */
export function resolveSwipeNav(
  pathname: string, dir: SwipeDirection, fromEdge: boolean,
): SwipeNav {
  const idx = tabIndexOf(pathname);
  if (idx >= 0) {
    // Палец влево — «тянем» следующую вкладку из-за правого края, и наоборот.
    const next = dir === "left" ? idx + 1 : idx - 1;
    if (next < 0 || next >= SWIPE_TABS.length) return null;   // край, без зацикливания
    return { kind: "tab", to: SWIPE_TABS[next] };
  }
  // Вложенный экран: назад — только жестом от левого края.
  if (dir === "right" && fromEdge) return { kind: "back" };
  return null;
}

/** Порог листания страницы заведомо больше карусельного (lib/carousel): цена
 *  ошибки выше — уносит с экрана целиком, а не на соседнее фото. Быстрый флик
 *  засчитываем по меньшему размаху: короткий резкий жест — тоже явное намерение. */
export function classifyPageSwipe(
  dx: number, dy: number, width: number, elapsedMs: number,
): SwipeDirection | null {
  const adx = Math.abs(dx);
  const ady = Math.abs(dy);
  if (adx <= ady * 1.5) return null;          // недостаточно горизонтальный — это скролл
  const flick = elapsedMs > 0 && elapsedMs < 250 && adx >= 44;
  if (!flick && adx < Math.max(64, width * 0.25)) return null;
  return dx < 0 ? "left" : "right";
}

