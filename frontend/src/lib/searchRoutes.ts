/** Куда ведёт строка поиска.
 *
 *  Раньше здесь жил РЕЖИМ («каталог» или «AI»), и тумблер рядом со строкой этот
 *  режим переключал. Переключение ничего не открывало: чтобы попасть в AI, надо
 *  было ещё нажать Enter. Со стороны это выглядело как «AI в поиске не
 *  работает» — человек нажал кнопку, что-то подсветилось, и всё.
 *
 *  Теперь режима нет вовсе: строка ВСЕГДА ищет по каталогу, кнопка ВСЕГДА
 *  открывает AI. Одно действие — один результат, гадать о состоянии не нужно.
 *
 *  Чистые функции и тесты в node — по той же причине, что и раньше: один и тот
 *  же обработчик Enter живёт в Home, Catalog и DesktopHeader, и четвёртая копия
 *  разъехалась бы с остальными.
 */

/** Обычный поиск по каталогу. */
export function catalogSearchRoute(query: string): string {
  const q = query.trim();
  return q ? `/catalog?query=${encodeURIComponent(q)}` : "/catalog";
}

/** Экран AI. С текстом — сразу отправляем его (`auto=1`).
 *
 *  Нажатие кнопки с уже набранным запросом — это явное «спроси про ЭТО», и
 *  заставлять человека нажимать «отправить» второй раз незачем. Тот же приём
 *  уже используется в кнопке «Спросить AI» поисковой панели, и второй способ
 *  открыть AI с запросом означал бы два разных поведения одного намерения.
 */
export function aiSearchRoute(query: string): string {
  const q = query.trim();
  return q ? `/ai?q=${encodeURIComponent(q)}&auto=1` : "/ai";
}
