/** Фильтры каталога (v5.6.0) — чистая логика, тестируется без DOM.
 *
 *  До этого мобильная витрина держала над первым товаром два ряда управления:
 *  категории и ещё семь элементов — три сортировки, два переключателя, выбор
 *  бренда и поле цены. Каждый по отдельности разумен, вместе они забирали
 *  примерно треть первого экрана и всем весом спорили с товаром, ради которого
 *  человек сюда пришёл.
 *
 *  Теперь второй ряд — две кнопки: текущая сортировка и «Фильтры» со
 *  счётчиком. Счётчик здесь не украшение: свёрнутый фильтр, о котором не
 *  напоминают, превращается в «каталог сломался, товаров мало». Число на
 *  кнопке — единственное, что об этом говорит, поэтому оно и живёт в отдельной
 *  функции с тестами.
 */

/** То, что уехало в шторку. Сортировка сюда НЕ входит: она есть всегда и
 *  выбрана всегда, а счётчик считает то, что человек включил сам. */
export type CatalogFilters = {
  onlyStock: boolean;
  onlyToday: boolean;
  /** Пустая строка — бренд не выбран. */
  brand: string;
  /** Строка, потому что приходит из поля ввода; пустая — ограничения нет. */
  priceMax: string;
};

export const EMPTY_FILTERS: CatalogFilters = {
  onlyStock: false,
  onlyToday: false,
  brand: "",
  priceMax: "",
};

/** Сколько фильтров сейчас сужают выдачу.
 *
 *  Пустая строка и строка из пробелов — это «не задано», а не значение: поле
 *  цены человек мог открыть и закрыть, ничего не введя. Ноль тоже не считаем
 *  фильтром: «цена до 0 ₽» не имеет смысла, а на кнопке дал бы единицу и
 *  отправил искать несуществующее ограничение. */
export function activeFilterCount(f: CatalogFilters): number {
  let n = 0;
  if (f.onlyStock) n += 1;
  if (f.onlyToday) n += 1;
  if (f.brand.trim()) n += 1;
  if (Number(f.priceMax) > 0) n += 1;
  return n;
}

export function hasActiveFilters(f: CatalogFilters): boolean {
  return activeFilterCount(f) > 0;
}

/** Подпись кнопки фильтров. Со счётчиком — только когда есть что считать:
 *  «Фильтры · 0» сообщало бы о нуле громче, чем о самой возможности фильтровать. */
export function filterButtonLabel(f: CatalogFilters): string {
  const n = activeFilterCount(f);
  return n > 0 ? `Фильтры · ${n}` : "Фильтры";
}

/** Подпись кнопки сортировки — сама выбранная сортировка, а не слово
 *  «Сортировка». Кнопка обязана отвечать на вопрос «как сейчас отсортировано»
 *  без нажатия: свёрнутый в неё выбор иначе становится невидимым. */
export function sortButtonLabel(
  sorts: ReadonlyArray<{ key: string; label: string }>,
  active: string,
  fallback = "Сортировка",
): string {
  return sorts.find((s) => s.key === active)?.label ?? fallback;
}
