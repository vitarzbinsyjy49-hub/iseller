/** Роудмап приложения — ОДИН список на все экраны.
 *
 *  Было три независимых массива (BetaRoadmapSheet, AiRoadmapSheet,
 *  LoyaltyRoadmapSheet), и они разъехались молча: «списание баллов в корзине»
 *  лежало и в бете, и в лояльности разными словами, с разным приоритетом.
 *  Теперь текст пункта существует ровно в одном месте, а экран — это фильтр.
 *
 *  СРОКИ ТЕПЕРЬ ЕСТЬ, но периодом, а не датой: «сентябрь», «октябрь», «позже».
 *  Прежнее правило «никаких сроков» было защитой от невыполнимого обещания;
 *  период держит ту же защиту (промах на неделю не выглядит обманом) и при
 *  этом отвечает на главный вопрос покупателя — «когда».
 *
 *  Пометки «следующий шаг» больше нет: её роль забрал период.
 *
 *  Чего здесь НЕТ и быть не должно:
 *  - оплаты картой и онлайн-оплаты. Магазин работает по договору комиссии,
 *    сделка идёт очно (см. AboutServiceSheet). Обещать онлайн-оплату — значит
 *    обещать смену юридической модели;
 *  - внутренних задач магазина (черновики постов для канала и т. п.):
 *    покупателю в роудмапе интересно только то, что меняет ЕГО опыт.
 */

