/** След работы AI: что система сделала, прежде чем ответить.
 *
 *  Строка собирается ТОЛЬКО из того, что backend реально вернул в `meta`, и из
 *  времени, замеренного на фронте. Ничего не досочиняем: это обещание такого же
 *  веса, как цена на карточке.
 *
 *  Чистая функция без React намеренно — весь разбор `meta` проверяется тестами
 *  без DOM, а компонент остаётся тонким.
 */
import type { AiAnswer } from "../components/ai/types";

/** Сколько человек ждал. Замер ФРОНТОВЫЙ, а не `meta.latency_ms`: тот меряет
 *  только работу сервера и всегда меньше пережитого ожидания. */
export function formatElapsed(ms: number): string {
  const safe = Number.isFinite(ms) && ms > 0 ? ms : 0;
  const sec = safe / 1000;
  if (sec < 1) {
    // Не бывает ответа за «0 с»: если ждали меньше десятой, показываем десятую.
    const tenths = Math.max(1, Math.round(sec * 10));
    // 0,95с округляется до десяти десятых — это целая секунда, а не «1,0 с».
    return tenths >= 10 ? "1 с" : `0,${tenths} с`;
  }
  const whole = Math.round(sec);
  // Таймаут фронта — 75с. «75 с» читается хуже, чем словами, а точность на
  // таком ожидании уже никому не нужна.
  return whole >= 60 ? "больше минуты" : `${whole} с`;
}

/** Подпись «над чем работаю» по РЕАЛЬНО прошедшему времени.
 *
 *  Пороги достались от прежней подписи под точками «печатает» и не меняются:
 *  обычный ответ укладывается в 3-15с, но при сетевом сбое на пути к гейтвею
 *  SDK делает до двух ретраев по 30с — без текста это читается как «зависло»,
 *  хотя запрос выполняется. Процентов и прогресса не выдумываем: знать их
 *  неоткуда, ответ приходит одним куском.
 */
export function runningLabel(elapsedMs: number): string {
  if (elapsedMs >= 16000) return "Сверяю наличие и цену";
  if (elapsedMs >= 4000) return "Подбираю варианты";
  return "Ищу в каталоге";
}

/** Русская плюрализация в винительном падеже: «просмотрел 1 позицию /
 *  2 позиции / 5 позиций». Тот же приём, что у `pluralItems` в cartMath. */
function pluralPositions(n: number): string {
  const abs = Math.abs(n) % 100;
  const last = abs % 10;
  if (abs > 10 && abs < 20) return `${n} позиций`;
  if (last === 1) return `${n} позицию`;
  if (last >= 2 && last <= 4) return `${n} позиции`;
  return `${n} позиций`;
}

/** `meta` ответа плюс прошедшее время -> строка следа, либо null, если следу
 *  нечего сообщить.
 *
 *  Правила проверяются СВЕРХУ ВНИЗ, до первого совпадения, и порядок здесь не
 *  косметика: при деградации backend ставит `degraded` и `source: "fallback"`
 *  ОДНОВРЕМЕННО, и от порядка зависит, какую из двух строк увидит человек.
 */
export function traceText(meta: AiAnswer["meta"] | undefined, elapsedMs: number): string | null {
  const m = meta ?? {};
  const time = formatElapsed(elapsedMs);

  // Простые интенты («привет», «как заказать») отвечаются мгновенно и без
  // каталога. Рассказывать тут нечего, а пустая строка следа выглядела бы как
  // недогруженная.
  if (m.source === "rules") return null;

  if (m.degraded) return `Упрощённый режим, подобрал из каталога · ${time}`;

  // Быстрый путь по каталогу опознаётся по ФЛАГУ: backend кладёт в source
  // строку "catalog", которой нет в союзе типа. Ориентироваться на значение
  // вне типа значит завести расхождение на ровном месте.
  if (m.skipped_llm) return `Нашёл в каталоге · ${time}`;

  if (m.source === "fallback") return `Ответил из каталога · ${time}`;
  if (m.source === "cache") return `Взял недавний ответ · ${time}`;
  if (m.source === "mock") return `Демо-режим · ${time}`;

  // Ноль кандидатов — не «просмотрел 0 позиций»: это читается как поломка,
  // хотя ответ может быть совершенно нормальным.
  if (typeof m.candidates === "number" && m.candidates > 0) {
    return `Просмотрел ${pluralPositions(m.candidates)} каталога · ${time}`;
  }
  return `Подобрал варианты · ${time}`;
}
