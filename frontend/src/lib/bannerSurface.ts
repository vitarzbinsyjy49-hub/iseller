/** Подложка баннера, взятая из самой фотографии.
 *
 *  ===== Зачем =====
 *
 *  Фотография с собственным фоном (а такие все, кроме вырезанных на прозрачном)
 *  на белой карточке висит прямоугольным блоком — то самое «дёшево выглядит».
 *  Если же залить карточку цветом, взятым у левого края этой самой фотографии,
 *  и растворить её левый край в него, блока не остаётся: снимок выглядит
 *  родным карточке, каким бы он ни был.
 *
 *  ===== Почему цвет текста считается, а не выбирается =====
 *
 *  Картинку загружает администратор, и она может быть какой угодно — от
 *  белого студийного фона до тёмно-синего. Любой захардкоженный цвет подписи
 *  однажды окажется нечитаемым, и узнаем мы об этом от покупателя. Поэтому
 *  цвет выводится из яркости подложки: правило одно на все картинки, включая
 *  те, которых ещё нет.
 *
 *  Чистые функции — сюда, работа с canvas — в компонент: так правило
 *  проверяется без браузера, как и остальная логика в этом каталоге.
 */

/** Откуда берём цвет: узкая полоска у ЛЕВОГО края.
 *
 *  Именно левого, потому что слева лежит текст: подложка обязана совпадать с
 *  тем, что под ним. Среднее по всей картинке дало бы цвет, которого у текста
 *  нет, — и на светлой слева / тёмной справа фотографии подпись оказалась бы
 *  на «средней» заливке, не совпадающей ни с чем. */
export const SURFACE_SAMPLE = { x: 0, width: 2, height: 24 } as const;

/** RGB как тройка. */
export type Rgb = [number, number, number];

/** Средний цвет выборки. null — брать нечего, подложку оставляем прежней.
 *
 *  Полностью прозрачные пиксели пропускаются: под ними в canvas лежит чёрный, и
 *  усреднив его вместе со всеми, мы получили бы подложку темнее картинки. У
 *  логотипов и вырезанных снимков с альфой это правило решает всё.
 */
export function edgeColor(data: Uint8ClampedArray): Rgb | null {
  let r = 0, g = 0, b = 0, n = 0;
  for (let i = 0; i + 3 < data.length; i += 4) {
    if (data[i + 3] === 0) continue;
    r += data[i]; g += data[i + 1]; b += data[i + 2]; n++;
  }
  if (n === 0) return null;
  return [Math.round(r / n), Math.round(g / n), Math.round(b / n)];
}

/** Относительная яркость по WCAG. Не сумма каналов: глаз видит зелёный втрое
 *  светлее синего при одинаковых числах, и по сумме текст на синем оказался бы
 *  тёмным — то есть нечитаемым. */
function luminance([r, g, b]: Rgb): number {
  const lin = [r, g, b].map((v) => {
    const c = v / 255;
    return c <= 0.04045 ? c / 12.92 : Math.pow((c + 0.055) / 1.055, 2.4);
  });
  return 0.2126 * lin[0] + 0.7152 * lin[1] + 0.0722 * lin[2];
}

/** Каким должен быть текст на этой подложке.
 *
 *  Порог 0.45, а не 0.5: спорная середина отдаётся СВЕТЛОМУ тексту. Белый на
 *  среднем сером читается лучше, чем почти-чёрный на нём же, — и ошибка в эту
 *  сторону стоит дешевле.
 */
export function inkOn(surface: Rgb): "dark" | "light" {
  return luminance(surface) > 0.45 ? "dark" : "light";
}
