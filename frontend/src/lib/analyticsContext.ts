/** Служебные поля, которые едут с КАЖДЫМ UI-событием: раскладка и платформа.
 *
 *  Зачем модуль. До него аналитика не знала, на каком экране происходит то,
 *  что она пишет. Доля десктопа и его конверсия были неизмеримы в принципе, и
 *  любая работа над широкими экранами шла бы вслепую: сказать «стало лучше»
 *  было бы не по чему.
 *
 *  Отдельная опасность, которую это скрывало: окно Mini App в Telegram Desktop
 *  часто уже 1024px, а брейкпоинт `lg` начинается ровно с 1024. Пока ширина не
 *  пишется, нельзя отличить «десктоп-раскладка слабая» от «десктоп-раскладку
 *  почти никто не видит» — а это два противоположных вывода о том, что делать.
 *
 *  Решение — в ОДНОЙ точке: поля подмешивает сам track(), и ни один из полусотни
 *  вызовов track по коду не знает о них и не правится. Обратное (передавать
 *  контекст руками) разошлось бы на первом же новом событии.
 *
 *  Чего здесь сознательно нет:
 *
 *  - точной ширины окна. Это элемент отпечатка браузера, а для решения, которое
 *    мы принимаем, хватает бакета. Писать больше, чем нужно для ответа, —
 *    плохая сделка в обе стороны;
 *  - user-agent по той же причине, только сильнее;
 *  - поведенческих событий рекомендаций (trackProduct). У них плоская схема с
 *    валидацией на бэкенде, лишние поля получат 422; и раскладка к подбору
 *    товаров отношения не имеет.
 */

/** Бакет раскладки. Границы — НЕ круглые числа «на глаз», а брейкпоинты, по
 *  которым вёрстка реально переключается (см. VIEWPORT_BREAKPOINTS). */
export type ViewportBucket = "xs" | "sm" | "md" | "lg";

/** Границы бакетов.
 *
 *  768 и 1024 — `md` и `lg` у Tailwind, 1440 — собственный `wide` проекта
 *  (tailwind.config.js). Совпадение обязательно: бакет отвечает на вопрос
 *  «какая раскладка была у человека в этот момент», и если границы разъедутся
 *  с брейкпоинтами, ответ станет неверным, оставаясь правдоподобным. Меняете
 *  брейкпоинт — меняйте и здесь.
 */
export const VIEWPORT_BREAKPOINTS = { sm: 768, md: 1024, lg: 1440 } as const;

/** Ширина окна → бакет раскладки.
 *
 *  Чистая функция: вся суть модуля проверяется без DOM и без браузера.
 *
 *  Ширина 0 и отрицательная приходят от свёрнутого окна и от фоновой вкладки.
 *  Падать на них нельзя — правило «аналитика никогда не должна ломать
 *  интерфейс» действует и здесь, — поэтому они попадают в xs: самый узкий
 *  бакет для самого узкого окна.
 */
export function viewportBucket(width: number): ViewportBucket {
  if (width >= VIEWPORT_BREAKPOINTS.lg) return "lg";
  if (width >= VIEWPORT_BREAKPOINTS.md) return "md";
  if (width >= VIEWPORT_BREAKPOINTS.sm) return "sm";
  return "xs";
}

/** Минимум, который нужен от окружения. Типы сужены до одного поля каждый —
 *  как в lib/navGlass.ts и по той же причине: тесты идут в node, и подставить
 *  сюда объект из одной строки дешевле, чем тянуть jsdom ради двух чтений. */
export type EventContextSources = {
  window: { innerWidth: number } | null;
  telegram: { platform?: string } | null;
};

/** Служебные поля события. Оба необязательны и оба могут быть null: вне
 *  браузера нет окна, вне Telegram нет платформы. Ни то, ни другое не повод
 *  не отправить событие. */
export type EventContext = {
  viewport: ViewportBucket | null;
  platform: string | null;
};

export function eventContext({ window, telegram }: EventContextSources): EventContext {
  return {
    viewport: window ? viewportBucket(window.innerWidth) : null,
    // `?? null`, а не `?.platform` напрямую: старые клиенты поля не отдают, и
    // undefined уехало бы в JSON как отсутствующий ключ, а в разборе — как
    // строка "undefined". Пустое значение должно быть одно и явное.
    platform: telegram?.platform ?? null,
  };
}
