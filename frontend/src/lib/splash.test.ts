import { describe, expect, it } from "vitest";
import { shouldHideSplash } from "./splash";

/** Заставка запуска снимается ровно в двух случаях, и второй легко забыть.
 *
 *  «Готово» очевидно. А вот «ошибка» — та самая ветка, пропуск которой даёт
 *  худший из возможных экранов: приложение УЖЕ знает, что войти не удалось, и
 *  нарисовало сообщение об этом, но человек видит поверх него бесконечно
 *  бегающую полосу загрузки. Отличить «грузится» от «сломалось навсегда» в
 *  этот момент нельзя ничем.
 */
describe("shouldHideSplash", () => {
  it("снимает заставку, когда приложение готово", () => {
    expect(shouldHideSplash("ready")).toBe(true);
  });

  it("снимает заставку и при ошибке входа — иначе она закроет сообщение", () => {
    expect(shouldHideSplash("error")).toBe(true);
  });

  it("держит заставку, пока идёт загрузка", () => {
    expect(shouldHideSplash("loading")).toBe(false);
  });
});
