/** Бейджи на плитке товара (v5.6.0) — чистая логика, тесты в node.
 *
 *  Раньше плитка рисовала все подходящие бейджи разом, и их набиралось до
 *  четырёх: «Легендарный», «Хит», скидка и «Б/у». Стопка из четырёх заливок
 *  ложилась поверх фотографии, то есть поверх единственного, ради чего плитка
 *  существует, — и переставала что-либо выделять: когда выделено всё, не
 *  выделено ничто.
 *
 *  Поэтому здесь не «какие бейджи подходят», а «какие ДВА важнее». Предел
 *  жёсткий и живёт в одном месте: стоит его размыть, и четвёрка вернётся сама
 *  собой, по одному бейджу за релиз.
 *
 *  Порядок приоритета — от самого редкого к самому общему:
 *
 *  1. «Легендарный» — единичные позиции, ради них плитка и отличается.
 *  2. Скидка — единственный бейдж с числом: он говорит не «обрати внимание»,
 *     а «вот на сколько дешевле», и проверяем его ценой рядом.
 *  3. «Хит» — мягкий сигнал спроса, его же несёт и социальное доказательство
 *     под ценой, так что потеря невелика.
 *  4. «Б/у» — состояние товара. Стоит последним не потому, что неважно, а
 *     потому, что цена подержанного и так выбивается из ряда; на самой
 *     карточке товара состояние названо прямо.
 */

export type CardBadgeKind = "legendary" | "discount" | "hot" | "used";

export type BadgeSource = {
  is_legendary?: boolean;
  is_hot?: boolean;
  condition?: "new" | "used" | "refurbished";
};

/** Сколько бейджей плитка показывает одновременно. */
export const MAX_CARD_BADGES = 2;

/** `discountPct` уже посчитан вызывающим (lib/format): здесь только отбор. */
export function cardBadges(card: BadgeSource, discountPercent: number | null): CardBadgeKind[] {
  const all: CardBadgeKind[] = [];
  if (card.is_legendary) all.push("legendary");
  if (discountPercent !== null && discountPercent > 0) all.push("discount");
  if (card.is_hot) all.push("hot");
  if (card.condition === "used") all.push("used");
  return all.slice(0, MAX_CARD_BADGES);
}
