/** Превращение «Добавить» → степпер: анимация слоя, который УХОДИТ.
 *
 *  Движение БОКОВОЕ, а не масштабом. Раньше кнопка сжималась и гасла на месте,
 *  а степпер всплывал поверх — два слоя в одной точке, и это читалось как
 *  «одно исчезло, другое появилось». Здесь происходит другое: один орган
 *  управления уступает место другому. Уступку показывает сдвиг вбок — кнопка
 *  уходит влево, степпер въезжает справа, как в корзине Ozon.
 *
 *  Приходящий слой играет enterRefCallback("slide") — он и так на rAF-моторе.
 *  Уходящему нужен эффект: он не появляется в DOM заново, а меняет состояние
 *  под собой, и поймать этот момент можно только сравнением с прошлым рендером.
 *
 *  useLayoutEffect, а не useEffect: React успевает применить data-hidden (в CSS
 *  это состояние покоя — прозрачность 0) до того, как эффект вернёт слою
 *  видимость. С обычным эффектом между коммитом и первым кадром анимации
 *  проскакивал бы кадр, где кнопка уже исчезла — то самое мигание, ради
 *  устранения которого всё и затевалось.
 *
 *  Первый рендер намеренно молчит: карточка товара, который УЖЕ в корзине,
 *  ничего не превращает — она просто такой открылась. Состояние покоя ей даёт
 *  CSS (.cart-morph-layer[data-hidden] в index.css).
 */
import { useLayoutEffect, useRef } from "react";
import { animateEnter, animateSwapOut } from "./motion";

/** Насколько слои расходятся вбок. Маленькое намеренно: это доводка, а не
 *  самостоятельное движение. Больше — и обмен превращается в переезд, который
 *  на плитке шириной в половину экрана выглядит суетой. */
export const CART_SWAP_DX_PX = 14;

export function useCartSwapOut<T extends HTMLElement>(added: boolean) {
  const ref = useRef<T>(null);
  const prevAdded = useRef(added);

  useLayoutEffect(() => {
    if (prevAdded.current === added) return;
    prevAdded.current = added;
    const el = ref.current;
    if (!el) return;
    // Стартовое значение ставим сами: слой мог остаться от прошлой анимации
    // с чужой прозрачностью, а анимация должна начинаться от видимого края.
    el.style.opacity = added ? "1" : "0";
    // Знаки зеркальны: кнопка уступает влево и возвращается оттуда же. Если
    // возвращать её справа, обратный ход выглядит не отменой действия, а новым
    // событием — и человек, нажавший «−» до нуля, видит не то, что отменил.
    const cancel = added
      ? animateSwapOut(el, undefined, -CART_SWAP_DX_PX)
      : animateEnter(el, "slide", undefined, 0, -CART_SWAP_DX_PX);

    // Отмена, возвращаемая lib/motion.ts, НАМЕРЕННО не доводит значение до
    // конца — это верно для прерванного ЖЕСТА (протяжку отпустили на
    // середине, и середина — законное состояние). Здесь другое: это не жест,
    // а одноразовое превращение с ровно двумя законными исходами (слой скрыт
    // /слой виден) — середина не бывает законной сама по себе.
    //
    // Ожидаемый путь отмены — сам следующий вызов этого эффекта при смене
    // `added`: он синхронно перезаписывает opacity/transform ДО своей
    // анимации (см. строку выше), так что до перерисовки браузер этот кадр не
    // увидит. Но если эффект обрывается по ЛЮБОЙ ДРУГОЙ причине —
    // размонтирование, HMR, что угодно, чего мы не предвидели — следующего
    // вызова не будет вовсе, и застывший на середине кадр останется на экране
    // навсегда: ровно тот баг, что ловится через getComputedStyle спустя
    // секунды после события. Поэтому на выходе из эффекта всегда доводим слой
    // до его законного отдыха для состояния, которое он играл: если анимация
    // уже дошла сама, это те же самые значения, и перезапись незаметна.
    return () => {
      cancel();
      el.style.opacity = added ? "0" : "1";
      el.style.transform = added ? `translate3d(${-CART_SWAP_DX_PX}px, 0, 0)` : "";
    };
  }, [added]);

  return ref;
}
