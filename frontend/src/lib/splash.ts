/** Заставка запуска: снятие того, что нарисовано в index.html.
 *
 *  Разметка и стили заставки живут в index.html, а не здесь и не в компоненте.
 *  Причина простая: всё, что рисует React, появляется уже ПОСЛЕ загрузки и
 *  разбора бандла — то есть ровно после паузы, которую заставка закрывает.
 *  Заставка из React закрывала бы пустоту, которой к тому моменту уже нет.
 *
 *  Отсюда и разделение, как у routeTransition / useRouteTransition: решение
 *  (`shouldHideSplash`) — чистая функция под тестом, работа с DOM (`hideSplash`)
 *  — тонкая обёртка без собственной логики.
 */

/** Состояние входа в приложение (см. App.tsx). */
export type AppStatus = "loading" | "ready" | "error";

/** Сколько длится уход заставки. Дублирует значение из index.html осознанно:
 *  там transition, здесь момент снятия узла. Разъехаться они могут только в
 *  одну сторону — узел исчезнет раньше, чем догорит переход, — и это видно
 *  глазом сразу же. */
export const SPLASH_FADE_MS = 260;

/** Пора ли снимать заставку.
 *
 *  «Ошибка» тут не менее важна, чем «готово»: при провале входа приложение
 *  рисует сообщение, и заставка поверх него превращает понятную ошибку в
 *  вечную загрузку. Ровно это решение и проверяется тестом.
 */
export function shouldHideSplash(status: AppStatus): boolean {
  return status !== "loading";
}

/** Снять заставку: затухание, затем удаление узла.
 *
 *  Идемпотентна. Вызывающему коду (эффект в App) проще вызывать её на каждый
 *  подходящий рендер, чем помнить, звали ли уже: повторный вызов не найдёт
 *  узла и тихо ничего не сделает.
 *
 *  Узел именно УДАЛЯЕТСЯ, а не остаётся прозрачным: полноэкранный слой с
 *  бесконечной анимацией внутри продолжал бы занимать композиторный слой и
 *  жечь батарею всё время работы приложения.
 */
export function hideSplash(): void {
  const el = typeof document !== "undefined" ? document.getElementById("app-splash") : null;
  if (!el || el.classList.contains("is-hiding")) return;
  el.classList.add("is-hiding");
  window.setTimeout(() => el.remove(), SPLASH_FADE_MS);
}
