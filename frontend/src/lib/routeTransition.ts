/** Переходы между маршрутами (v5.6.0) — чистая логика, тестируется без DOM.
 *
 *  Направление берём из той же модели, что и свайп-навигация (lib/pageSwipe):
 *  приложение делится на ПЛОСКОСТЬ и ГЛУБИНУ, и переход обязан читаться так же,
 *  как жест, которым его вызывают.
 *
 *  - Пять корневых вкладок — плоскость. Соседняя вкладка приезжает с той
 *    стороны, где она лежит в BottomNav: «Каталог» правее «Главной», значит
 *    едет справа. Затемнения нет — вкладки равноправны, одна не «под» другой.
 *  - Вложенный экран — глубина. Вперёд: новый приходит справа во всю ширину,
 *    старый уходит влево на треть и притемняется — он остался под ним. Назад:
 *    верхний уезжает вправо целиком, нижний возвращается с той же трети в ноль.
 *
 *  Треть, а не полная ширина, у нижнего слоя — это и есть параллакс: два слоя
 *  движутся с разной скоростью, и глаз читает, который из них дальше. Замерено
 *  по видео Ozon: нижний экран проходит примерно 30% ширины за то же время.
 */
import { tabIndexOf } from "./pageSwipe";

/** Откуда приезжает НОВЫЙ экран. */
export type EnterFrom = "left" | "right";

export type RouteMotion =
  /** Переход без движения: тот же маршрут, replace или «уменьшить движение». */
  | { kind: "none" }
  /** Вложенность: параллакс + затемнение уходящего вперёд. */
  | { kind: "depth"; enterFrom: EnterFrom }
  /** Соседняя вкладка: оба слоя идут на всю ширину, без затемнения. */
  | { kind: "tab"; enterFrom: EnterFrom };

/** Тип последней записи в истории — как его отдаёт useNavigationType(). */
export type HistoryAction = "PUSH" | "POP" | "REPLACE";

/** Длительности. Замеры по видео Ozon: pop укладывается в 200–270 мс.
 *
 *  Это НЕ «мало» и увеличивать их не нужно. Плавность даёт кривая и то, что
 *  между слоями никогда не видно пустоты; длительность отвечает за другое — за
 *  скорость отклика. Переход длиннее ~300 мс перестаёт читаться как движение
 *  интерфейса и начинается читаться как задержка приложения. */
export const DEPTH_MS = 240;
export const TAB_MS = 200;

/** Доля ширины, которую проходит НИЖНИЙ слой (в процентах). */
export const PARALLAX_PCT = 30;

/** Какое движение показать при переходе from → to. */
export function resolveRouteMotion(from: string, to: string, action: HistoryAction): RouteMotion {
  // Тот же маршрут (смена только query/hash) — экран не меняется, двигать нечего.
  if (from === to) return { kind: "none" };
  // replace — это не шаг по истории, а подмена текущей записи (деплинк при
  // старте, нормализация адреса). Направления у неё нет, и придумывать его
  // значит показывать движение там, где пользователь никуда не переходил.
  if (action === "REPLACE") return { kind: "none" };

  const fromTab = tabIndexOf(from);
  const toTab = tabIndexOf(to);
  if (fromTab >= 0 && toTab >= 0) {
    return { kind: "tab", enterFrom: toTab > fromTab ? "right" : "left" };
  }

  // Всё остальное — глубина. POP всегда назад: и нативная кнопка Telegram, и
  // свайп от края, и системный жест браузера приходят сюда одинаково.
  return { kind: "depth", enterFrom: action === "POP" ? "left" : "right" };
}

export function routeMotionDuration(motion: RouteMotion): number {
  return motion.kind === "tab" ? TAB_MS : DEPTH_MS;
}

/** Смещения слоёв в процентах ширины экрана.
 *
 *  `enter` — стартовое положение входящего (к нулю он и едет).
 *  `exit`  — конечное положение уходящего (стартует он из нуля).
 *
 *  Знак: минус — влево, плюс — вправо. */
export function routeMotionOffsets(motion: RouteMotion): { enter: number; exit: number } {
  if (motion.kind === "none") return { enter: 0, exit: 0 };
  const sign = motion.enterFrom === "right" ? 1 : -1;

  if (motion.kind === "tab") {
    // Плоскость: оба слоя идут на всю ширину, как листание.
    return { enter: sign * 100, exit: -sign * 100 };
  }

  // Глубина. Верхний слой всегда проходит всю ширину, нижний — только треть.
  return motion.enterFrom === "right"
    // Вперёд: входящий сверху (100), уходящий снизу (треть влево).
    ? { enter: 100, exit: -PARALLAX_PCT }
    // Назад: уходящий сверху (вся ширина вправо), входящий снизу (треть слева).
    : { enter: -PARALLAX_PCT, exit: 100 };
}

/** Затемняется ли уходящий слой.
 *
 *  Только когда он уходит ПОД новый экран. На возврате уходящий слой — верхний,
 *  он и так покидает экран целиком; притемнять то, что уезжает, незачем. */
export function dimsExitingLayer(motion: RouteMotion): boolean {
  return motion.kind === "depth" && motion.enterFrom === "right";
}

/** Непрозрачность затемнения в конце перехода. Заметно глазу как «слой ниже»,
 *  но не настолько, чтобы уходящий экран выглядел выключенным. */
export const DIM_OPACITY = 0.16;
