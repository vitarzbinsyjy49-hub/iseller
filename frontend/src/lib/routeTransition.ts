/** Переходы между маршрутами (v5.6.0) — чистая логика, тестируется без DOM.
 *
 *  Сдвиг есть ТОЛЬКО между корневыми вкладками. Всё остальное — вход в карточку
 *  товара, в избранное, в историю и возврат оттуда — идёт мягким проявлением,
 *  без движения и без снимка уходящего экрана.
 *
 *  Так решено по итогам проверки на живом устройстве. Вход вглубь показывал
 *  два скачка вместо движения: между уходящим экраном и приехавшей карточкой
 *  вклинивался промежуточный кадр. Причина в том, что вложенный экран
 *  подгружается отдельным chunk'ом и запрашивает свои данные — то есть к началу
 *  движения его ещё нет, и содержимое меняется прямо посреди анимации. Сдвиг
 *  этот момент не сглаживает, а подчёркивает: он обещает непрерывность, которой
 *  под ним нет.
 *
 *  У вкладок такой беды не бывает: они уже загружены, их данные закэшированы,
 *  и соседняя вкладка приезжает готовой.
 *
 *  Направление для вкладок берём из той же модели, что и свайп-навигация
 *  (lib/pageSwipe): вкладки — ПЛОСКОСТЬ, и соседняя приезжает с той стороны,
 *  где она лежит в BottomNav. Переход обязан читаться так же, как жест, которым
 *  его вызывают.
 *
 *  (Раньше здесь был ещё режим «глубина» с параллаксом и затемнением нижнего
 *  слоя. Он снят целиком, а не оставлен выключенным: неиспользуемая ветка молча
 *  расходится с остальным кодом. История правки — в git.)
 */
import { tabIndexOf } from "./pageSwipe";

/** Откуда приезжает НОВЫЙ экран. */
export type EnterFrom = "left" | "right";

export type RouteMotion =
  /** Без движения: проявление вместо сдвига. */
  | { kind: "none" }
  /** Соседняя вкладка: оба слоя идут на всю ширину, навстречу друг другу. */
  | { kind: "tab"; enterFrom: EnterFrom };

/** Тип последней записи в истории — как его отдаёт useNavigationType(). */
export type HistoryAction = "PUSH" | "POP" | "REPLACE";

/** Длительность сдвига.
 *
 *  Замеры по нативному поведению: переход укладывается в 200–270 мс. Это НЕ
 *  «мало» и увеличивать это не нужно. Плавность даёт кривая и то, что между
 *  слоями не видно пустоты; длительность отвечает за другое — за скорость
 *  отклика. Переход длиннее ~300 мс перестаёт читаться как движение интерфейса
 *  и начинает читаться как задержка приложения. */
export const TAB_MS = 200;

/** Какое движение показать при переходе from → to. */
export function resolveRouteMotion(from: string, to: string, action: HistoryAction): RouteMotion {
  // Тот же маршрут (сменились только query/hash) — экран не меняется.
  if (from === to) return { kind: "none" };
  // replace — не шаг по истории, а подмена текущей записи (деплинк при старте,
  // нормализация адреса). Направления у неё нет, и придумывать его значит
  // показывать движение там, где пользователь никуда не переходил.
  if (action === "REPLACE") return { kind: "none" };

  const fromTab = tabIndexOf(from);
  const toTab = tabIndexOf(to);
  if (fromTab < 0 || toTab < 0) return { kind: "none" };

  return { kind: "tab", enterFrom: toTab > fromTab ? "right" : "left" };
}

export function routeMotionDuration(motion: RouteMotion): number {
  return motion.kind === "tab" ? TAB_MS : 0;
}

/** Смещения слоёв в процентах ширины экрана.
 *
 *  `enter` — стартовое положение входящего (к нулю он и едет).
 *  `exit`  — конечное положение уходящего (стартует он из нуля).
 *
 *  Знак: минус — влево, плюс — вправо. Вкладки равноправны, поэтому оба слоя
 *  проходят одинаковый путь навстречу друг другу: ни один не «под» другим. */
export function routeMotionOffsets(motion: RouteMotion): { enter: number; exit: number } {
  if (motion.kind === "none") return { enter: 0, exit: 0 };
  const sign = motion.enterFrom === "right" ? 1 : -1;
  return { enter: sign * 100, exit: -sign * 100 };
}
