/** Единая точка решения про стекло нижней навигации.
 *
 *  Зачем модуль. Стекло на нижней панели — не оформление, а зависимость от
 *  того, что под ней. Панель показывает СВОЁ РАЗМЫТИЕ ФОНА, поэтому вопрос
 *  «включать ли стекло» — это на самом деле три разных вопроса, и решать их
 *  россыпью по компонентам означает получить те же шесть независимых ответов,
 *  что когда-то получила настройка «уменьшить движение» (см. lib/motion.ts).
 *
 *  Три причины отказаться, и все три обязательны:
 *
 *  1. Браузер не умеет backdrop-filter. Тогда полупрозрачная панель — это не
 *     стекло, а мутное окно, сквозь которое читаются едущие карточки. Честнее
 *     быть сплошной. Ровно тот же вывод уже сделан для шапки главной
 *     (@supports-блок у .app-navbar в index.css).
 *
 *  2. Под панелью стоит непрозрачная панель страницы (.cta-dock — кнопка
 *     «Оставить заявку» на карточке товара, строка ввода AI, шаги визарда
 *     продажи). Её фон идёт ДО САМОГО НИЗА, за навбаром — это осознанное
 *     решение против сквозной щели над навигацией (разобрано в index.css).
 *     Значит размывать там нечего: стекло показало бы сплошной прямоугольник
 *     вместо контента. Внешне это выглядит как «стекло сломалось», хотя
 *     работает ровно как задумано.
 *
 *  3. Цена размытия. Раньше .nav-surface была почти сплошной именно поэтому:
 *     «остаётся читаемой без дорогого blur в Telegram WebView». Стекло
 *     возвращается только там, где за него есть чем заплатить, и снимается
 *     переменной окружения без правки компонентов.
 *
 *  Чего здесь СОЗНАТЕЛЬНО нет — варианта «спрятать панель». Отказ от стекла
 *  это отказ от МАТЕРИАЛА, а не от навигации: панель остаётся на месте и
 *  остаётся читаемой, меняется только её подложка. Та же развилка, что в
 *  motion.ts: «убрать движение» — не «убрать событие».
 */

/** Чем залита нижняя панель. `solid` — прежний почти сплошной фон. */
export type NavSurface = "glass" | "solid";

/** Селектор непрозрачных панелей страницы, которые стоят ПОД навигацией и
 *  закрашивают всё до нижней кромки. Тот же класс, которым они объявляются в
 *  index.css и который уже ищет lib/useRouteTransition.ts (PINNABLE_SELECTOR).
 *  Держим одну строку, чтобы список не разъехался на два места. */
export const OPAQUE_DOCK_SELECTOR = ".cta-dock";

/** Умеет ли браузер размывать подложку.
 *
 *  Проверяется оба написания: в Telegram WebView на iOS живёт исключительно
 *  префиксный вариант, и проверка только по неспрефиксному объявила бы стекло
 *  недоступным ровно там, где оно как раз работает лучше всего.
 */
export function supportsBackdropFilter(): boolean {
  if (typeof window === "undefined" || !window.CSS || !window.CSS.supports) return false;
  return (
    window.CSS.supports("backdrop-filter", "blur(1px)") ||
    window.CSS.supports("-webkit-backdrop-filter", "blur(1px)")
  );
}

/** Минимум, который нужен от DOM, чтобы ответить на вопрос.
 *
 *  Тип сужен до одного метода намеренно: тесты этого проекта идут в node без
 *  DOM, и подставить сюда заглушку из двух строк дешевле, чем тянуть в
 *  зависимости jsdom ради одной проверки `querySelector`. */
export type DockQuery = { querySelector(selectors: string): unknown };

/** Стоит ли сейчас на странице непрозрачная панель, закрывающая фон под
 *  навигацией. Читается из живого DOM, а не из маршрута: панель объявляет себя
 *  сама (классом), и список маршрутов, которые её показывают, пришлось бы
 *  держать вторым источником правды и синхронизировать вручную. */
export function hasOpaqueDock(
  root: DockQuery | null = typeof document === "undefined" ? null : document,
): boolean {
  if (!root) return false;
  return root.querySelector(OPAQUE_DOCK_SELECTOR) != null;
}

/** Входные данные решения — каждое поле отвечает за одну причину отказа. */
export type NavSurfaceInput = {
  /** Браузер умеет backdrop-filter. */
  supported: boolean;
  /** Под навигацией стоит непрозрачная панель страницы. */
  dockBehind: boolean;
};

/** Чем заливать панель при данных условиях. Чистая функция: весь смысл модуля
 *  проверяется тестами без DOM и без браузера.
 *
 *  Отката «через переменную окружения» здесь нет намеренно. Vite запекает
 *  import.meta.env на сборке, поэтому такой рубильник всё равно потребовал бы
 *  пересборки и деплоя — ровно того же, что правка одной строки CSS, только с
 *  лишним механизмом и типами, которых в этом фронтенде больше нигде нет.
 *  Если стекло окажется дорогим на живых телефонах, откат — снять data-glass
 *  в BottomNav.tsx или убрать @supports-блок .nav-row[data-glass="on"]
 *  .nav-surface в index.css; прежнее сплошное состояние при этом остаётся
 *  нетронутым.
 */
export function navSurface({ supported, dockBehind }: NavSurfaceInput): NavSurface {
  if (!supported) return "solid";
  if (dockBehind) return "solid";
  return "glass";
}
