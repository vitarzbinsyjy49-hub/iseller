/** Перетаскивание шторки пальцем (v5.8.0) — чистая логика, тесты в node.
 *
 *  Шторка обязана следовать за пальцем, а не просто появляться и исчезать.
 *  Причина не в красоте: у наших шторок СВЕРХУ УЖЕ НАРИСОВАНА ручка — та серая
 *  полоска. Она ничего не делала, то есть интерфейс обещал жест, которого нет.
 *  Обещание, которое элемент даёт формой, дороже любой анимации.
 *
 *  Модель разделена надвое намеренно:
 *
 *  - ПОКА палец на экране движение прямое, кадр в кадр со смещением пальца.
 *    Это не анимация, а прямое управление: любое сглаживание здесь читается как
 *    залипание, потому что человек видит собственную руку и сравнивает с ней.
 *  - ПОСЛЕ отпускания — анимация: либо доводим до края и закрываем, либо
 *    возвращаем на место. Вот она уже считается покадрово, как всё в lib/motion.
 *
 *  Вверх шторка тоже отзывается, но не уезжает: она и так на своей высоте, и
 *  пускать её выше — значит открывать пустоту над ней. Вместо этого сопротивление
 *  (см. RUBBER_LIMIT_PX): жест не игнорируется, но и не обещает того, чего нет.
 */

/** Дальше этого шторка вверх не уходит, как бы сильно ни тянули. */
export const RUBBER_LIMIT_PX = 28;

/** Доля высоты, после которой отпускание закрывает шторку. */
export const DISMISS_RATIO = 0.28;

/** Скорость (px/мс), при которой закрываем, не дожидаясь полного пути.
 *  Быстрый короткий флик — такое же явное намерение, как долгое протягивание;
 *  тот же принцип, что у свайпа между страницами (lib/pageSwipe). */
export const DISMISS_VELOCITY = 0.5;

/** Ниже этого пути закрытие по скорости не срабатывает ВООБЩЕ.
 *
 *  Одной скорости мало: палец, дрогнувший на десяток пикселей за пару
 *  миллисекунд, даёт скорость в разы выше порога — и шторка закрывалась бы от
 *  дрожания руки при обычном тапе. Поймано на проверке: отпускание на 12px
 *  закрывало панель. Флик обязан быть и быстрым, и хоть сколько-то длинным. */
export const DISMISS_MIN_PX = 32;

/** На сколько шторка реально смещена при смещении пальца на `dy`.
 *
 *  Вниз — один к одному: палец и панель не должны расходиться.
 *  Вверх — с затуханием, асимптотически к RUBBER_LIMIT_PX: смещение есть всегда
 *  (жест не проигнорирован), но чем сильнее тянут, тем меньше отдача. */
export function sheetDragOffset(dy: number): number {
  if (dy >= 0) return dy;
  const pulled = -dy;
  return -RUBBER_LIMIT_PX * (1 - 1 / (1 + pulled / RUBBER_LIMIT_PX));
}

/** Непрозрачность подложки, пока шторку тянут вниз.
 *
 *  Гаснет вместе с уходом панели: подложка — это «за шторкой что-то есть», и
 *  держать её на полной силе, когда шторка уже наполовину ушла, значит
 *  показывать затемнение без причины. Ниже нуля не опускаем. */
export function sheetBackdropOpacity(offset: number, height: number): number {
  if (offset <= 0 || height <= 0) return 1;
  return Math.max(0, 1 - offset / height);
}

export type DragEnd = {
  /** Смещение панели в момент отпускания (px, вниз — положительное). */
  offset: number;
  /** Высота панели (px). */
  height: number;
  /** Сколько длился жест (мс) — для скорости. */
  elapsedMs: number;
};

/** Закрыть или вернуть на место.
 *
 *  Два независимых основания, и оба нужны. По одному пути закрывать нельзя:
 *  быстрый флик вниз проходит мало и был бы отменён вопреки очевидному
 *  намерению. По одной скорости — тоже: медленное, но долгое протягивание в
 *  самый низ ничем иным, кроме закрытия, быть не может. */
export function shouldDismissSheet({ offset, height, elapsedMs }: DragEnd): boolean {
  if (offset <= 0 || height <= 0) return false;
  if (offset >= height * DISMISS_RATIO) return true;
  if (offset < DISMISS_MIN_PX) return false;
  const velocity = elapsedMs > 0 ? offset / elapsedMs : 0;
  return velocity >= DISMISS_VELOCITY;
}

/** Считать ли жест вертикальным (а не прокруткой вбок или случайным дрожанием).
 *
 *  Порог по вертикали отсекает дрожание пальца при обычном тапе: без него
 *  нажатие на кнопку внутри шторки начинало бы её тащить. Сравнение с
 *  горизонталью отсекает боковые ленты внутри шторки — там жест адресован им. */
export const DRAG_START_PX = 6;

export function isVerticalDrag(dx: number, dy: number): boolean {
  return Math.abs(dy) >= DRAG_START_PX && Math.abs(dy) > Math.abs(dx);
}

/** Зона у верхней кромки, откуда шторку можно тянуть ВСЕГДА — независимо от
 *  того, прокручено ли её содержимое. Ровно здесь нарисована ручка, и жест за
 *  ручку обязан работать даже посреди прокрученного списка: она за тем и
 *  нарисована. 44px — та же минимальная цель касания, что у всего остального.
 *  Вынесена сюда вместе со scrollerWithin — обе используются только парой. */
export const HANDLE_ZONE_PX = 44;

/** Ближайший прокручиваемый предок внутри панели — или null, если такого нет.
 *
 *  Нужен, чтобы отличить «тянут шторку» от «прокручивают её содержимое»: пока
 *  списку есть куда прокручиваться вверх, жест вниз адресован ему, а не
 *  шторке. Раньше жила только в ScenarioSheet.tsx (SheetShell) — вынесена сюда
 *  при переезде поиска в нижний ряд навигации: у выдачи над рядом та же
 *  развилка (список результатов внутри панели), а второй копии этой проверки
 *  заводить незачем — она уже отлажена и её достаточно переиспользовать.
 */
export function scrollerWithin(target: EventTarget | null, panel: HTMLElement): HTMLElement | null {
  let el = target instanceof HTMLElement ? target : null;
  while (el && el !== panel.parentElement) {
    if (el.scrollHeight > el.clientHeight + 1) {
      const overflowY = getComputedStyle(el).overflowY;
      if (overflowY === "auto" || overflowY === "scroll") return el;
    }
    if (el === panel) break;
    el = el.parentElement;
  }
  return null;
}
