/** GSAP под правилами этого проекта.
 *
 *  Зачем библиотека, когда есть свой мотор. lib/motion.ts умеет вести число от
 *  A до B покадрово — этого хватает для проявлений, сдвигов и налива стекла.
 *  Чего он не умеет и не должен: FLIP — превращение одного элемента в другой
 *  через замер их реальных позиций. Именно это делает переходы между экранами
 *  «дорогими»: карточка не сменяется страницей товара, а разворачивается в неё.
 *  Писать свой FLIP означало бы писать заново то, что у GSAP отлажено годами.
 *
 *  Почему именно GSAP, а не Motion и не View Transitions. Этот webview гасит
 *  ДЕКЛАРАТИВНУЮ анимацию целиком — CSS-переходы и WAAPI здесь не «быстрее», а
 *  замирают на стартовом кадре (поймано трижды: панель каталога, кнопка-степпер,
 *  стекло навигации). Motion по умолчанию едет на WAAPI, View Transitions —
 *  декларативный по своей природе. GSAP считает всё сам на requestAnimationFrame,
 *  то есть ровно тем же способом, что и наш мотор, и переживает то же, что
 *  переживает он.
 *
 *  Цена измерена на нашей сборке: gsap + Flip дают +96 KB сырых, +37 KB gzip.
 *  Поэтому импортировать его ТОЧЕЧНО, в тех местах, где нужен FLIP, а не
 *  переводить на него всё движение приложения: проявления и сдвиги наш мотор
 *  делает бесплатно, и платить за них второй раз незачем.
 *
 *  Этот файл — не обёртка ради обёртки. Он держит три правила, которые библиотека
 *  сама соблюдать не обязана, а проект обязан:
 *
 *  1. «Уменьшить движение» — не украшение. Движение снимается, состояние
 *     остаётся: элемент обязан оказаться в конечной позиции, а не замереть.
 *  2. В СКРЫТОЙ вкладке rAF не выполняется ВООБЩЕ. Значит анимация не
 *     завершится никогда, а вместе с ней не наступит и её onComplete — и всё,
 *     что от него зависит, повиснет. Смотреть в этот момент некому, поэтому
 *     ставим конечное состояние сразу.
 *  3. Анимируем только transform и opacity. Всё остальное composited-слой не
 *     считает, а значит вызывает перерисовку на каждом кадре.
 */
import { gsap } from "gsap";
import { Flip } from "gsap/Flip";

import { prefersReducedMotion } from "./motion";

gsap.registerPlugin(Flip);

/** Пружина без отскока: доезжает с весом, но не пружинит обратно.
 *
 *  «Дороже» ощущается именно за счёт неравномерности: движение стартует резко и
 *  долго доводится. Отскок (back/elastic) сюда не берём — на продуктовом
 *  интерфейсе он читается как игрушечность, а не как качество. */
export const EASE_PREMIUM = "power3.out";

/** То же для ухода: короче и суше входа — уходящее не несёт информации. */
export const EASE_PREMIUM_OUT = "power2.in";

/** Играть ли движение вообще, или сразу поставить конечное состояние.
 *
 *  Вынесено отдельной функцией, а не спрятано в каждом вызове: это решение
 *  проекта, а не деталь конкретной анимации, и проверяется оно тестом.
 */
export function shouldSkipMotion(
  reducedMotion = prefersReducedMotion(),
  hidden = typeof document !== "undefined" && document.hidden,
): boolean {
  return reducedMotion || hidden;
}

/** Превращение одного состояния раскладки в другое (FLIP).
 *
 *  `mutate` обязан синхронно поменять DOM — добавить класс, переставить узел,
 *  сменить разметку. Позиции ДО замеряются перед ним, ПОСЛЕ — сразу за ним, и
 *  разница отыгрывается трансформом. Браузер считает раскладку один раз; каждый
 *  кадр после этого — только transform.
 *
 *  Возвращает функцию отмены — как и всё в lib/motion.ts, чтобы вызывающий мог
 *  оборвать движение из cleanup эффекта, не оставив узел на полпути.
 */
export function flipMorph(
  targets: Element | Element[] | string,
  mutate: () => void,
  { durationMs = 320, ease = EASE_PREMIUM }: { durationMs?: number; ease?: string } = {},
): () => void {
  if (shouldSkipMotion()) {
    mutate();
    return () => {};
  }
  const state = Flip.getState(targets);
  mutate();
  const tl = Flip.from(state, {
    duration: durationMs / 1000,
    ease,
    // Свойства, которые Flip доводит сам. Никаких layout-свойств: только то,
    // что композитор считает без перерисовки.
    absolute: true,
    nested: true,
  });
  return () => { tl.kill(); };
}

/** Точечная анимация transform/opacity с премиальной кривой.
 *
 *  Тонкая обёртка нужна ровно ради двух вещей: снятия движения при «уменьшить
 *  движение» и мгновенного финала в скрытой вкладке. Без них GSAP оставил бы
 *  узел на стартовом кадре навсегда — ровно та беда, от которой в этом webview
 *  страдает декларативная анимация.
 */
export function tweenTo(
  el: Element,
  to: gsap.TweenVars,
  { durationMs = 260, ease = EASE_PREMIUM }: { durationMs?: number; ease?: string } = {},
): () => void {
  if (shouldSkipMotion()) {
    gsap.set(el, to);
    return () => {};
  }
  const tw = gsap.to(el, { ...to, duration: durationMs / 1000, ease });
  return () => { tw.kill(); };
}

export { gsap, Flip };
